using System;
using System.Collections.Generic;
using System.Linq;
using Houtamelo.Spire.Analyzers.SourceGenerators.Model;

namespace Houtamelo.Spire.Analyzers.SourceGenerators.Emit;

/// Emits one public payload struct per variant and the union's runtime storage.
/// Concrete unmanaged payloads retain runtime-selected layout; generation does
/// not calculate user type sizes or alignments.
internal static class VariantPayloadEmitter
{
    public static string Emit(UnionDeclaration union)
    {
        var variants = union.Variants.ToList();
        var layout = StorageLayout.Create(union, variants);
        var sb = new SourceBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        GeneratedAliasEmitter.Emit(
            sb,
            union,
            layout.HasUnmanagedFields,
            layout.HasUnmanagedFields || layout.HasManagedFields);
        sb.AppendLine();

        var hasNamespace = !string.IsNullOrEmpty(union.Namespace);
        if (hasNamespace)
            sb.OpenNamespace(union.Namespace);

        sb.OpenContainingTypes(union.ContainingTypes);
        EmitUnion(sb, union, variants, layout);
        sb.AppendLine();
        EmitTypes(sb, union, variants, layout);
        sb.CloseContainingTypes(union.ContainingTypes);
        if (hasNamespace)
            sb.CloseNamespace();
        return sb.ToString();
    }

    private static void EmitTypes(
        SourceBuilder sb,
        UnionDeclaration union,
        IReadOnlyList<VariantInfo> variants,
        StorageLayout layout)
    {
        sb.AppendLine($"{ContainerAccess(union.AccessibilityKeyword)}static class {IdentifierUtility.Escape(TypesName(union))}");
        sb.OpenBrace();
        if (layout.HasUnmanagedFields || layout.HasManagedFields)
        {
            EmitFields(sb, union, layout);
            sb.EnsureBlankLine();
        }
        EmitVariants(sb, union, variants);
        sb.CloseBrace();
    }

    private static void EmitFields(SourceBuilder sb, UnionDeclaration union, StorageLayout layout)
    {
        sb.AppendLine("internal static class Fields");
        sb.OpenBrace();
        if (layout.HasManagedFields)
        {
            sb.AppendLine("internal struct Managed");
            sb.OpenBrace();
            foreach (var slot in layout.Slots.Where(slot => slot.IsManaged))
            {
                var attribute = union.EmitUnitySerialization
                    ? $"[{GeneratedAliasEmitter.AttributeReference(union, "NonSerialized", "global::System.NonSerializedAttribute")}] "
                    : string.Empty;
                sb.AppendLine($"{attribute}internal {slot.TypeName} _s{slot.Index};");
            }
            sb.CloseBrace();
        }
        if (layout.HasUnmanagedFields)
        {
            if (layout.HasManagedFields)
                sb.EnsureBlankLine();
            var structLayout = GeneratedAliasEmitter.AttributeReference(
                union,
                "StructLayout",
                "global::System.Runtime.InteropServices.StructLayoutAttribute");
            var layoutKind = GeneratedAliasEmitter.Reference(
                union,
                "LayoutKind",
                "global::System.Runtime.InteropServices.LayoutKind");
            sb.AppendLine($"[{structLayout}({layoutKind}.Explicit)]");
            sb.AppendLine("internal struct Unmanaged");
            sb.OpenBrace();
            foreach (var entry in layout.UnmanagedVariants)
            {
                sb.AppendLine("[global::System.Runtime.InteropServices.FieldOffset(0)]");
                var attribute = union.EmitUnitySerialization
                    ? $"[{GeneratedAliasEmitter.AttributeReference(union, "NonSerialized", "global::System.NonSerializedAttribute")}] "
                    : string.Empty;
                sb.AppendLine($"{attribute}internal {IdentifierUtility.Escape(entry.TypeName)} {IdentifierUtility.Escape(entry.FieldName)};");
            }

            foreach (var entry in layout.UnmanagedVariants)
            {
                sb.EnsureBlankLine();
                sb.AppendLine($"[{structLayout}({layoutKind}.Auto)]");
                sb.AppendLine($"internal struct {IdentifierUtility.Escape(entry.TypeName)}");
                sb.OpenBrace();
                foreach (var field in entry.Fields)
                {
                    var attribute = union.EmitUnitySerialization
                        ? $"[{GeneratedAliasEmitter.AttributeReference(union, "NonSerialized", "global::System.NonSerializedAttribute")}] "
                        : string.Empty;
                    sb.AppendLine($"{attribute}internal {field.TypeFullName} {IdentifierUtility.Escape(field.Name)};");
                }
                sb.CloseBrace();
            }
            sb.CloseBrace();
        }
        sb.CloseBrace();
    }

    private static void EmitVariants(SourceBuilder sb, UnionDeclaration union, IReadOnlyList<VariantInfo> variants)
    {
        sb.AppendLine("public static class Variants");
        sb.OpenBrace();
        foreach (var variant in variants)
        {
            EmitPayloadType(sb, union, variant, variant.Name);
            if (HasAlias(variant))
                EmitPayloadType(sb, union, variant, variant.FormerlySerializedAs!);
        }
        sb.CloseBrace();
    }

    private static void EmitPayloadType(
        SourceBuilder sb,
        UnionDeclaration union,
        VariantInfo variant,
        string variantName)
    {
        var name = IdentifierUtility.SerializedName(variantName);
        var typeParams = DeclarationFormatting.FormatEscapedTypeParameters(union.TypeParameters);
        var constraints = DeclarationFormatting.FormatConstraints(union.TypeParameterConstraints);
        if (union.EmitUnitySerialization)
            sb.AppendLine($"[{GeneratedAliasEmitter.AttributeReference(union, "Preserve", "global::UnityEngine.Scripting.PreserveAttribute")}]");
        sb.AppendLine($"[{GeneratedAliasEmitter.AttributeReference(union, "Serializable", "global::System.SerializableAttribute")}]");
        sb.AppendLine($"public struct {IdentifierUtility.Escape(name)}{typeParams}{constraints}");
        sb.OpenBrace();
        for (var index = 0; index < variant.Fields.Length; index++)
        {
            var field = variant.Fields[index];
            var attributes = new List<string>();
            if (union.EmitUnitySerialization && !field.IsUnityManagedReference)
                attributes.Add($"[{GeneratedAliasEmitter.AttributeReference(union, "SerializeField", "global::UnityEngine.SerializeField")}]");
            if (union.EmitUnitySerialization && field.IsUnityManagedReference)
                attributes.Add($"[{GeneratedAliasEmitter.AttributeReference(union, "SerializeReference", "global::UnityEngine.SerializeReference")}]");
            sb.AppendLine($"{string.Join(" ", attributes)}{(attributes.Count == 0 ? string.Empty : " ")}{field.TypeFullName} {BackingFieldName(field)};");
            sb.AppendLine($"public readonly {field.TypeFullName} {IdentifierUtility.Escape(field.Name)} => {BackingFieldName(field)};");
            if (index + 1 < variant.Fields.Length)
                sb.EnsureBlankLine();
        }

        if (variant.Fields.Length > 0)
        {
            var parameters = string.Join(", ", variant.Fields.Select(field =>
                $"{field.TypeFullName} {IdentifierUtility.Escape(field.Name)}"));
            sb.AppendLine();
            sb.AppendLine($"public {IdentifierUtility.Escape(name)}({parameters})");
            sb.OpenBrace();
            foreach (var field in variant.Fields)
            {
                var fieldName = IdentifierUtility.Escape(field.Name);
                sb.AppendLine($"this.{BackingFieldName(field)} = {fieldName};");
            }
            sb.CloseBrace();
        }

        var deconstructParameters = string.Join(", ", variant.Fields.Select(field =>
            $"out {field.TypeFullName} {IdentifierUtility.Escape(field.Name)}"));
        if (variant.Fields.Length == 0)
        {
            sb.AppendLine("public readonly void Deconstruct() {}");
        }
        else
        {
            sb.AppendLine();
            sb.AppendLine($"public readonly void Deconstruct({deconstructParameters})");
            sb.OpenBrace();
            foreach (var field in variant.Fields)
            {
                var fieldName = IdentifierUtility.Escape(field.Name);
                sb.AppendLine($"{fieldName} = this.{BackingFieldName(field)};");
            }
            sb.CloseBrace();
        }
        sb.CloseBrace();
        sb.AppendLine();
    }

    private static void EmitUnion(SourceBuilder sb, UnionDeclaration union, IReadOnlyList<VariantInfo> variants, StorageLayout layout)
    {
        var typeParams = DeclarationFormatting.FormatEscapedTypeParameters(union.TypeParameters);
        var constraints = DeclarationFormatting.FormatConstraints(union.TypeParameterConstraints);
        var unionType = IdentifierUtility.Escape(union.TypeName) + typeParams;
        var access = Access(union.AccessibilityKeyword);
        var readonlyModifier = union.IsReadonly && !union.EmitUnitySerialization ? "readonly " : string.Empty;
        var refModifier = union.IsRefStruct ? "ref " : string.Empty;
        sb.AppendLine($"[{GeneratedAliasEmitter.AttributeReference(union, "EnforceInitialization", "global::Houtamelo.Spire.EnforceInitializationAttribute")}]");
        var unityInterface = union.EmitUnitySerialization
            ? $", {GeneratedAliasEmitter.Reference(union, "ISerializationCallbackReceiver", "global::UnityEngine.ISerializationCallbackReceiver")}"
            : string.Empty;
        const string unionInterface = "global::Houtamelo.Spire.IDiscriminatedUnion";
        var interfaces = union.IsRefStruct
            ? string.Empty
            : $" : {unionInterface}<{unionType}.Kind>{unityInterface}";
        sb.AppendLine($"{access}{readonlyModifier}{refModifier}partial {union.DeclarationKeyword} {unionType}{interfaces}{constraints}");
        sb.OpenBrace();

        sb.AppendLine($"[{GeneratedAliasEmitter.AttributeReference(union, "EnforceExhaustiveness", "global::Houtamelo.Spire.EnforceExhaustivenessAttribute")}]");
        sb.AppendLine($"public enum Kind : {KindType(variants.Count)}");
        sb.OpenBrace();
        foreach (var variant in variants)
            sb.AppendLine($"{IdentifierUtility.Escape(variant.Name)},");
        sb.CloseBrace();
        sb.AppendLine();
        if (union.EmitUnitySerialization)
        {
            var serializeField = GeneratedAliasEmitter.AttributeReference(
                union,
                "SerializeField",
                "global::UnityEngine.SerializeField");
            sb.AppendLine($"[{serializeField}] Kind _kind;");
        }
        else
            sb.AppendLine("readonly Kind _kind;");
        sb.AppendLine("public readonly Kind kind => _kind;");
        if (layout.HasUnmanagedFields)
        {
            var attribute = union.EmitUnitySerialization
                ? $"[{GeneratedAliasEmitter.AttributeReference(union, "NonSerialized", "global::System.NonSerializedAttribute")}] "
                : string.Empty;
            sb.AppendLine($"{attribute}readonly {FieldsReference(union)}.Unmanaged __unmanaged;");
        }
        if (layout.HasManagedFields)
        {
            var attribute = union.EmitUnitySerialization
                ? $"[{GeneratedAliasEmitter.AttributeReference(union, "NonSerialized", "global::System.NonSerializedAttribute")}] "
                : string.Empty;
            sb.AppendLine($"{attribute}readonly {FieldsReference(union)}.Managed __managed;");
        }
        foreach (var slot in layout.Slots.Where(slot => !slot.IsManaged))
        {
            var attribute = union.EmitUnitySerialization
                ? $"[{GeneratedAliasEmitter.AttributeReference(union, "NonSerialized", "global::System.NonSerializedAttribute")}] "
                : string.Empty;
            sb.AppendLine($"{attribute}readonly {slot.TypeName} _s{slot.Index};");
        }
        if (union.EmitUnitySerialization)
            UnitySerializationEmitter.EmitVariantSerializedStorage(sb, union);
        sb.AppendLine();

        EmitConstructor(sb, union, layout);
        sb.AppendLine();
        EmitFactories(sb, union, variants, layout);
        sb.AppendLine();
        EmitAccessors(sb, union, variants, layout);
        sb.AppendLine();
        foreach (var variant in variants)
            sb.AppendLine($"public readonly bool {IdentifierUtility.Escape("Is" + variant.Name)} => kind == Kind.{IdentifierUtility.Escape(variant.Name)};");
        sb.AppendLine();
        EmitToString(sb, union, variants, layout);
        if (union.EmitUnitySerialization)
        {
            sb.EnsureBlankLine();
            UnitySerializationEmitter.EmitVariantPayloadCallbacks(sb, union, unionType);
        }
        sb.CloseBrace();
    }

    private static void EmitConstructor(SourceBuilder sb, UnionDeclaration union, StorageLayout layout)
    {
        var unionType = IdentifierUtility.Escape(union.TypeName) + DeclarationFormatting.FormatEscapedTypeParameters(union.TypeParameters);
        var parameters = new List<string> { "Kind kind" };
        if (layout.HasUnmanagedFields)
            parameters.Add($"{FieldsReference(union)}.Unmanaged unmanaged");
        if (layout.HasManagedFields)
            parameters.Add($"{FieldsReference(union)}.Managed managed");
        parameters.AddRange(layout.Slots.Where(slot => !slot.IsManaged).Select(slot => $"{slot.TypeName} s{slot.Index}"));
        sb.AppendLine($"{IdentifierUtility.Escape(union.TypeName)}({string.Join(", ", parameters)})");
        sb.OpenBrace();
        sb.AppendLine("this = default;");
        sb.AppendLine("_kind = kind;");
        if (layout.HasUnmanagedFields)
            sb.AppendLine("__unmanaged = unmanaged;");
        if (layout.HasManagedFields)
            sb.AppendLine("__managed = managed;");
        foreach (var slot in layout.Slots.Where(slot => !slot.IsManaged))
            sb.AppendLine($"_s{slot.Index} = s{slot.Index};");
        sb.CloseBrace();
    }

    private static void EmitFactories(SourceBuilder sb, UnionDeclaration union, IReadOnlyList<VariantInfo> variants, StorageLayout layout)
    {
        var unionType = IdentifierUtility.Escape(union.TypeName) + DeclarationFormatting.FormatEscapedTypeParameters(union.TypeParameters);
        for (var index = 0; index < variants.Count; index++)
        {
            var variant = variants[index];
            var parameters = string.Join(", ", variant.Fields.Select(field =>
                $"{field.TypeFullName} {IdentifierUtility.Escape(field.Name)}"));
            sb.AppendLine($"{Access(variant.AccessibilityKeyword)}static partial {unionType} {IdentifierUtility.Escape(variant.Name)}({parameters})");
            sb.OpenBrace();
            var localNames = new LocalNameAllocator(union, variant);
            var arguments = new List<string> { $"Kind.{IdentifierUtility.Escape(variant.Name)}" };
            var suppressNullabilityWarnings = layout.RequiresNullabilitySuppression(variant);
            if (suppressNullabilityWarnings)
                sb.AppendLine("#pragma warning disable CS8619, CS8620 // Nullable annotations are erased; this is a direct typed-slot transfer.");

            if (layout.HasUnmanagedFields)
                arguments.Add(EmitUnmanagedFactoryLocal(sb, union, variant, layout, localNames));
            if (layout.HasManagedFields)
                arguments.Add(EmitManagedFactoryLocal(sb, union, variant, layout, localNames));
            for (var i = 0; i < layout.Slots.Count; i++)
            {
                if (layout.Slots[i].IsManaged)
                    continue;
                var field = layout.GetFieldForSlot(variant, i);
                var localName = localNames.Next("storage" + i);
                EmitTypedSlotLocal(sb, layout.Slots[i], field, localName);
                arguments.Add(localName);
            }

            sb.AppendLine($"return new {unionType}({string.Join(", ", arguments)});");
            if (suppressNullabilityWarnings)
                sb.AppendLine("#pragma warning restore CS8619, CS8620");
            sb.CloseBrace();
            if (index + 1 < variants.Count)
                sb.EnsureBlankLine();
        }
    }

    private static string EmitUnmanagedFactoryLocal(
        SourceBuilder sb,
        UnionDeclaration union,
        VariantInfo variant,
        StorageLayout layout,
        LocalNameAllocator localNames)
    {
        var entry = layout.UnmanagedVariants.FirstOrDefault(item => item.VariantName == variant.Name);
        var overlayType = $"{FieldsReference(union)}.Unmanaged";
        var overlayName = localNames.Next("unmanagedFields");
        if (entry is null)
        {
            sb.AppendLine($"{overlayType} {overlayName} = default;");
            return overlayName;
        }

        var variantName = localNames.Next(
            FieldNameResolver.CamelCase(IdentifierUtility.SerializedName(variant.Name)) + "Fields");
        var assignments = entry.Fields.Select(field =>
            $"{IdentifierUtility.Escape(field.Name)} = {IdentifierUtility.Escape(field.Name)}");
        sb.AppendLine($"var {variantName} = new {FieldsReference(union)}.Unmanaged.{IdentifierUtility.Escape(entry.TypeName)} {{ {string.Join(", ", assignments)} }};");
        sb.AppendLine($"var {overlayName} = new {overlayType} {{ {IdentifierUtility.Escape(entry.FieldName)} = {variantName} }};");
        return overlayName;
    }

    private static string EmitManagedFactoryLocal(
        SourceBuilder sb,
        UnionDeclaration union,
        VariantInfo variant,
        StorageLayout layout,
        LocalNameAllocator localNames)
    {
        var managedName = localNames.Next("managedFields");
        var assignments = layout.Slots
            .Where(slot => slot.IsManaged)
            .Select(slot =>
            {
                var field = layout.GetFieldForSlot(variant, slot.Index);
                if (field is null)
                    return $"_s{slot.Index} = default!";
                var value = IdentifierUtility.Escape(field.Name);
                return $"_s{slot.Index} = {value}";
            });
        sb.AppendLine($"var {managedName} = new {FieldsReference(union)}.Managed {{ {string.Join(", ", assignments)} }};");
        return managedName;
    }

    private static void EmitTypedSlotLocal(
        SourceBuilder sb,
        StorageLayout.Slot slot,
        FieldInfo? field,
        string localName)
    {
        if (field is null)
        {
            sb.AppendLine($"{slot.TypeName} {localName} = default!;");
            return;
        }

        sb.AppendLine($"var {localName} = {IdentifierUtility.Escape(field.Name)};");
    }

    private static void EmitAccessors(SourceBuilder sb, UnionDeclaration union, IReadOnlyList<VariantInfo> variants, StorageLayout layout)
    {
        var factoryNames = variants.Select(variant => variant.Name).ToArray();
        for (var index = 0; index < variants.Count; index++)
        {
            var variant = variants[index];
            var propertyName = VariantNaming.AccessorName(variant.Name, factoryNames);
            var payloadType = GeneratedAliasEmitter.VariantPayloadReference(union, variant.Name);
            var values = variant.Fields.Select(field => layout.GetFieldExpression(union, variant, field));
            var editorBrowsable = GeneratedAliasEmitter.AttributeReference(
                union,
                "EditorBrowsable",
                "global::System.ComponentModel.EditorBrowsableAttribute");
            var editorBrowsableState = GeneratedAliasEmitter.Reference(
                union,
                "EditorBrowsableState",
                "global::System.ComponentModel.EditorBrowsableState");
            sb.AppendLine($"[{editorBrowsable}({editorBrowsableState}.Never)]");
            if (layout.RequiresNullabilitySuppression(variant))
                sb.AppendLine("#pragma warning disable CS8619, CS8620 // Nullable annotations are erased; this is a direct typed-slot read.");
            var debugType = union.EmitUnitySerialization
                ? "global::UnityEngine.Debug"
                : "global::System.Diagnostics.Debug";
            var variantDisplayName = IdentifierUtility.SerializedName(variant.Name);
            var message = CSharpStringLiteral.EscapeContent(
                $"Accessing the `{variantDisplayName}` variant's fields is only allowed when `kind == Kind.{variantDisplayName}`. Actual kind: {{this._kind}}");
            sb.AppendLine($"public readonly {payloadType} {IdentifierUtility.Escape(propertyName)}");
            sb.OpenBrace();
            sb.AppendLine("get");
            sb.OpenBrace();
            sb.AppendLine($"{debugType}.Assert(this._kind == Kind.{IdentifierUtility.Escape(variant.Name)}, $\"{message}\");");
            sb.AppendLine($"return new {payloadType}({string.Join(", ", values)});");
            sb.CloseBrace();
            sb.CloseBrace();
            if (layout.RequiresNullabilitySuppression(variant))
                sb.AppendLine("#pragma warning restore CS8619, CS8620");
            if (index + 1 < variants.Count)
                sb.EnsureBlankLine();
        }
    }

    private static void EmitToString(SourceBuilder sb, UnionDeclaration union, IReadOnlyList<VariantInfo> variants, StorageLayout layout)
    {
        if (variants.Any(layout.RequiresNullabilitySuppression))
            sb.AppendLine("#pragma warning disable CS8619, CS8620 // Nullable annotations are erased; formatting reads the direct typed slot.");
        sb.AppendLine("public override readonly string ToString() => kind switch");
        sb.OpenBrace();
        foreach (var variant in variants)
        {
            var name = IdentifierUtility.SerializedName(variant.Name);
            if (variant.Fields.Length == 0)
            {
                sb.AppendLine($"Kind.{IdentifierUtility.Escape(variant.Name)} => \"{name}()\",");
                continue;
            }

            var values = variant.Fields.Select(field => layout.GetFieldExpression(union, variant, field));
            sb.AppendLine($"Kind.{IdentifierUtility.Escape(variant.Name)} => $\"{name}({string.Join(", ", values.Select(value => "{" + value + "}"))})\",");
        }
        sb.AppendLine($"_ => \"{IdentifierUtility.SerializedName(union.TypeName)}(?)\",");
        sb.CloseBrace(";");
        if (variants.Any(layout.RequiresNullabilitySuppression))
            sb.AppendLine("#pragma warning restore CS8619, CS8620");
    }

    private static bool HasAlias(VariantInfo variant)
        => variant.HasFormerlySerializedAs;
    private static string TypesName(UnionDeclaration union)
        => GeneratedAliasEmitter.TypesName(union);

    private static string FieldsReference(UnionDeclaration union)
        => GeneratedAliasEmitter.FieldsReference(union);
    private static string Access(string accessibility)
        => DeclarationFormatting.FormatAccessibility(accessibility);
    private static string ContainerAccess(string accessibility)
        => accessibility switch
        {
            "private" => string.Empty,
            "protected" => "protected ",
            "private protected" => "private protected ",
            "protected internal" => "protected internal ",
            "internal" => "internal ",
            "public" => "public ",
            _ => string.Empty,
        };
    private static string KindType(int count) => count <= byte.MaxValue ? "byte" : count <= ushort.MaxValue ? "ushort" : "int";

    private static string Safe(string name)
    {
        var raw = IdentifierUtility.SerializedName(name);
        var chars = raw
            .Select(character => char.IsLetterOrDigit(character) || character == '_' ? character : '_')
            .ToArray();
        return chars.Length == 0 ? "Value" : new string(chars);
    }

    internal static string BackingFieldName(FieldInfo field)
        => "_" + IdentifierUtility.SerializedName(field.Name);

    private sealed class StorageLayout
    {
        internal sealed class Slot
        {
            public int Index;
            public string TypeName = string.Empty;
            public string Key = string.Empty;
            public bool IsShared;
            public bool IsManaged;
            public Dictionary<string, FieldInfo> FieldsByVariant = new(StringComparer.Ordinal);
        }

        internal sealed class UnmanagedVariant
        {
            public string VariantName = string.Empty;
            public string TypeName = string.Empty;
            public string FieldName = string.Empty;
            public List<FieldInfo> Fields = new();
        }

        internal readonly List<Slot> Slots = new();
        internal readonly List<UnmanagedVariant> UnmanagedVariants = new();
        internal bool HasUnmanagedFields => UnmanagedVariants.Count > 0;
        internal bool HasManagedFields => Slots.Any(slot => slot.IsManaged);

        internal static StorageLayout Create(UnionDeclaration union, IReadOnlyList<VariantInfo> variants)
        {
            var result = new StorageLayout();
            var unmanagedTypeNames = new HashSet<string>(
                variants
                    .Where(variant => variant.Fields.Any(field => field.IsUnmanaged && !field.IsGenericDependent))
                    .Select(variant => Safe(variant.Name))
                    .Where(name => name != "Unmanaged"),
                StringComparer.Ordinal);
            foreach (var variant in variants)
            {
                var fields = variant.Fields.Where(field => field.IsUnmanaged && !field.IsGenericDependent).ToList();
                if (fields.Count == 0)
                    continue;
                var typeName = UniqueUnmanagedTypeName(variant.Name, unmanagedTypeNames);
                result.UnmanagedVariants.Add(new UnmanagedVariant
                {
                    VariantName = variant.Name,
                    TypeName = typeName,
                    FieldName = "__" + FieldNameResolver.CamelCase(IdentifierUtility.SerializedName(variant.Name)),
                    Fields = fields,
                });
            }

            var allFallback = variants.SelectMany(variant => variant.Fields.Select(field => new FieldUse(variant, field)))
                .Where(use => !use.Field.IsUnmanaged || use.Field.IsGenericDependent)
                .ToList();
            var candidates = allFallback.Where(use => !use.Field.IsGenericDependent).ToList();
            var useShared = union.ReferenceStorage == ReferenceStorage.Shared ||
                union.ReferenceStorage == ReferenceStorage.Auto && ShouldShare(candidates);
            if (useShared)
                AddSharedSlots(result, allFallback, candidates);
            else
                AddTypedSlots(result, allFallback);
            return result;
        }

        private static string UniqueUnmanagedTypeName(string variantName, ISet<string> usedNames)
        {
            var baseName = Safe(variantName);
            if (baseName != "Unmanaged")
                return baseName;

            var candidateBase = baseName == "Unmanaged" ? "UnmanagedVariant" : baseName;
            var candidate = candidateBase;
            var suffix = 2;
            while (candidate == "Unmanaged" || !usedNames.Add(candidate))
                candidate = candidateBase + suffix++;
            return candidate;
        }

        private static bool ShouldShare(IReadOnlyList<FieldUse> candidates)
        {
            if (candidates.Count == 0)
                return false;
            var typed = candidates.GroupBy(use => TypeKey(use.Field), StringComparer.Ordinal)
                .Sum(group => group.GroupBy(use => use.Variant.Name, StringComparer.Ordinal).Max(grouping => grouping.Count()));
            var shared = candidates.GroupBy(use => use.Variant.Name, StringComparer.Ordinal)
                .Max(group => group.Count());
            return shared * 2 <= typed;
        }

        private static void AddTypedSlots(StorageLayout result, IReadOnlyList<FieldUse> uses)
        {
            foreach (var group in uses.GroupBy(use => TypeKey(use.Field), StringComparer.Ordinal))
            {
                var max = group.GroupBy(use => use.Variant.Name, StringComparer.Ordinal)
                    .Select(grouping => grouping.Count()).DefaultIfEmpty().Max();
                for (var index = 0; index < max; index++)
                    result.Slots.Add(CreateSlot(result, group, index, false, !group.First().Field.IsGenericDependent));
            }
        }

        private static void AddSharedSlots(StorageLayout result, IReadOnlyList<FieldUse> allFallback, IReadOnlyList<FieldUse> candidates)
        {
            foreach (var group in allFallback.Where(use => use.Field.IsGenericDependent)
                .GroupBy(use => TypeKey(use.Field), StringComparer.Ordinal))
            {
                var max = group.GroupBy(use => use.Variant.Name, StringComparer.Ordinal)
                    .Select(grouping => grouping.Count()).DefaultIfEmpty().Max();
                for (var index = 0; index < max; index++)
                    result.Slots.Add(CreateSlot(result, group, index, false, false));
            }
            var maxShared = candidates.GroupBy(use => use.Variant.Name, StringComparer.Ordinal)
                .Select(group => group.Count()).DefaultIfEmpty().Max();
            for (var index = 0; index < maxShared; index++)
            {
                var slot = new Slot { Index = result.Slots.Count, TypeName = "object?", Key = "object", IsShared = true, IsManaged = true };
                foreach (var use in candidates)
                {
                    var ordinal = Ordinal(candidates, use);
                    if (ordinal == index)
                        slot.FieldsByVariant[use.Variant.Name] = use.Field;
                }
                result.Slots.Add(slot);
            }
        }

        private static Slot CreateSlot(StorageLayout result, IGrouping<string, FieldUse> group, int index, bool shared, bool managed)
        {
            var slot = new Slot { Index = result.Slots.Count, TypeName = SlotTypeName(group), Key = group.Key, IsShared = shared, IsManaged = managed };
            foreach (var use in group)
            {
                if (Ordinal(group, use) == index)
                    slot.FieldsByVariant[use.Variant.Name] = use.Field;
            }
            return slot;
        }

        private static string SlotTypeName(IGrouping<string, FieldUse> group)
        {
            return group.Select(use => use.Field.StorageTypeFullName)
                .FirstOrDefault(type => type is not null)
                ?? group.First().Field.TypeFullName;
        }

        private static int Ordinal(IEnumerable<FieldUse> sequence, FieldUse target)
        {
            var ordinal = 0;
            foreach (var candidate in sequence)
            {
                if (candidate.Variant.Name != target.Variant.Name)
                    continue;
                if (ReferenceEquals(candidate, target))
                    return ordinal;
                ordinal++;
            }
            return -1;
        }

        internal FieldInfo? GetFieldForSlot(VariantInfo variant, int index)
            => Slots[index].FieldsByVariant.TryGetValue(variant.Name, out var field) ? field : null;

        internal bool RequiresNullabilitySuppression(VariantInfo variant)
        {
            foreach (var field in variant.Fields)
            {
                var slot = Slots.FirstOrDefault(candidate =>
                    candidate.FieldsByVariant.TryGetValue(variant.Name, out var value) &&
                    ReferenceEquals(value, field));
                if (slot is not null &&
                    !slot.IsShared &&
                    field.StorageTypeFullName is { } storageType &&
                    !string.Equals(field.TypeFullName, storageType, StringComparison.Ordinal))
                {
                    return true;
                }
            }
            return false;
        }

        internal string GetFieldExpression(UnionDeclaration union, VariantInfo variant, FieldInfo field)
        {
            var unmanaged = UnmanagedVariants.FirstOrDefault(item => item.VariantName == variant.Name &&
                item.Fields.Any(candidate => candidate.Name == field.Name));
            if (unmanaged is not null)
                return $"__unmanaged.{IdentifierUtility.Escape(unmanaged.FieldName)}.{IdentifierUtility.Escape(field.Name)}";

            var slot = Slots.FirstOrDefault(candidate => candidate.FieldsByVariant.TryGetValue(variant.Name, out var value) &&
                ReferenceEquals(value, field));
            if (slot is null)
                slot = Slots.FirstOrDefault(candidate => candidate.FieldsByVariant.TryGetValue(variant.Name, out var value) && value.Name == field.Name);
            if (slot is null)
                return "default!";
            var storage = slot.IsManaged ? $"__managed._s{slot.Index}" : $"_s{slot.Index}";
            if (!slot.IsShared)
                return storage;
            if (field.IsReferenceType)
                return $"({field.TypeFullName}){storage}!";
            return $"({storage} is null ? default({field.TypeFullName}) : ({field.TypeFullName}){storage})";
        }

        private sealed record FieldUse(VariantInfo Variant, FieldInfo Field);
        private static string TypeKey(FieldInfo field) => field.ConstructorTypeKey ?? field.TypeFullName.TrimEnd('?');
    }

    private sealed class LocalNameAllocator
    {
        private readonly HashSet<string> _used = new(StringComparer.Ordinal);

        internal LocalNameAllocator(UnionDeclaration union, VariantInfo variant)
        {
            foreach (var field in variant.Fields)
                Reserve(field.Name);
            foreach (var parameter in union.TypeParameters)
                Reserve(parameter);
            foreach (var containingType in union.ContainingTypes)
            {
                foreach (var parameter in containingType.TypeParameters)
                    Reserve(parameter);
            }
        }

        internal string Next(string baseName)
        {
            var candidate = baseName;
            var suffix = 2;
            while (!_used.Add(IdentifierUtility.SerializedName(candidate)))
                candidate = baseName + suffix++;
            return candidate;
        }

        private void Reserve(string name)
            => _used.Add(IdentifierUtility.SerializedName(name));
    }
