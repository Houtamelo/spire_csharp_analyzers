using System.Collections.Generic;
using System.Linq;
using Houtamelo.Spire.Analyzers.SourceGenerators.Model;

namespace Houtamelo.Spire.Analyzers.SourceGenerators.Emit;

internal static class OverlapEmitter
{
    public static string Emit(UnionDeclaration union)
        => EmitCore(union, unitySerialization: false);

    internal static string EmitUnity(UnionDeclaration union)
        => EmitCore(union, unitySerialization: true);

    private static string EmitCore(UnionDeclaration union, bool unitySerialization)
    {
        var sb = new SourceBuilder();
        var kindSize = OverlapLayoutComputer.KindSize(union.Variants.Length);
        var layout = OverlapLayoutComputer.ComputeLayout(
            union.Variants, kindSize);

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Runtime.InteropServices;");
        if (unitySerialization)
            sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using System.ComponentModel;");
        sb.AppendLine();

        var hasNamespace = !string.IsNullOrEmpty(union.Namespace);
        if (hasNamespace)
        {
            sb.AppendLine($"namespace {union.Namespace}");
            sb.OpenBrace();
        }

        sb.OpenContainingTypes(union.ContainingTypes);

        var accessMod = string.IsNullOrEmpty(union.AccessibilityKeyword) ? "" : union.AccessibilityKeyword + " ";
        var readonlyMod = union.IsReadonly ? "readonly " : "";
        var refMod = union.IsRefStruct ? "ref " : "";

        sb.AppendLine("[global::Houtamelo.Spire.EnforceInitialization]");
        sb.AppendLine($"[StructLayout(LayoutKind.Explicit)]");
        var unityInterface = unitySerialization
            ? ", global::UnityEngine.ISerializationCallbackReceiver"
            : "";
        sb.AppendLine($"{accessMod}{readonlyMod}{refMod}partial {union.DeclarationKeyword} {union.TypeName} : global::Houtamelo.Spire.IDiscriminatedUnion<{union.TypeName}.Kind>{unityInterface}");
        sb.OpenBrace();

        EmitKindEnum(sb, union);
        sb.AppendLine();
        // Kind field (backing field + property)
        sb.AppendLine("[FieldOffset(0)]");
        if (unitySerialization)
        {
            sb.AppendLine("[global::System.NonSerialized]");
            sb.AppendLine($"private Kind {UnitySerializationEmitter.RuntimeKindFieldName};");
        }
        else
        {
            sb.AppendLine("readonly Kind _kind;");
        }
        sb.AppendLine($"public Kind kind => this.{(unitySerialization ? UnitySerializationEmitter.RuntimeKindFieldName : "_kind")};");
        sb.AppendLine();

        EmitGlobalFields(sb, layout, unitySerialization);
        if (unitySerialization)
            EmitSerializedStorage(sb, layout);
        if (unitySerialization)
            EmitGlobalConstructor(sb, union.TypeName, unitySerialization);
        else
            EmitOrdinaryConstructors(sb, union);
        sb.AppendLine();
        EmitGlobalFactories(sb, union, layout, unitySerialization);
        if (union.GenerateDeconstruct)
            EmitGlobalDeconstructs(sb, union.Variants, layout);
        EmitProperties(sb, layout, union.HasInitProperties, unitySerialization);

        // IsVariant properties
        foreach (var variant in union.Variants)
            sb.AppendLine($"public bool Is{variant.Name} => this.kind == Kind.{IdentifierUtility.Escape(variant.Name)};");

        if (unitySerialization)
        {
            var resetStatements = new List<string>();
            foreach (var field in layout.GlobalR1)
                resetStatements.Add($"this._{field.Name} = default!;");
            foreach (var field in layout.GlobalR2)
                resetStatements.Add($"this._{field.Name} = default!;");
            foreach (var field in layout.GlobalR3)
                resetStatements.Add($"this._obj_{field.Name} = default!;");

            UnitySerializationEmitter.EmitCallbacksAndPayloads(
                sb,
                union,
                union.TypeName,
                resetStatements);
        }

        ToStringEmitter.EmitStructToString(sb, union);

        sb.CloseBrace(); // type

        sb.CloseContainingTypes(union.ContainingTypes);

        if (hasNamespace)
            sb.CloseBrace(); // namespace

        return sb.ToString();
    }

    private static void EmitKindEnum(SourceBuilder sb, UnionDeclaration union)
    {
        var kindType = OverlapLayoutComputer.KindTypeName(union.Variants.Length);
        sb.AppendLine($"public enum Kind : {kindType}");
        sb.OpenBrace();
        foreach (var variant in union.Variants)
            sb.AppendLine($"{IdentifierUtility.Escape(variant.Name)},");
        sb.CloseBrace();
    }

    private static void EmitGlobalFields(
        SourceBuilder sb,
        OverlapLayoutInfo layout,
        bool unitySerialization)
    {
        // Internal storage must be fields (not auto-properties) because the
        // generated constructors initialize them directly.
        foreach (var gf in layout.GlobalR1)
        {
            sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");
            if (unitySerialization)
                sb.AppendLine("[global::System.NonSerialized]");
            sb.AppendLine($"[FieldOffset({gf.Offset})]");
            sb.AppendLine(unitySerialization
                ? $"internal {gf.TypeFullName} _{gf.Name};"
                : $"internal readonly {gf.TypeFullName} _{gf.Name};");
            sb.AppendLine();
        }

        foreach (var gf in layout.GlobalR2)
        {
            int offset = layout.R2Offset + gf.Offset * 8;
            sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");
            if (unitySerialization)
                sb.AppendLine("[global::System.NonSerialized]");
            sb.AppendLine($"[FieldOffset({offset})]");
            sb.AppendLine(unitySerialization
                ? $"internal {NullableReferenceType(gf.TypeFullName)} _{gf.Name};"
                : $"internal readonly {NullableReferenceType(gf.TypeFullName)} _{gf.Name};");
            sb.AppendLine();
        }

        foreach (var gf in layout.GlobalR3)
        {
            int offset = layout.R3Offset + gf.Offset * 8;
            sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");
            if (unitySerialization)
                sb.AppendLine("[global::System.NonSerialized]");
            sb.AppendLine($"[FieldOffset({offset})]");
            sb.AppendLine(unitySerialization
                ? $"internal object? _obj_{gf.Name};"
                : $"internal readonly object? _obj_{gf.Name};");
            sb.AppendLine();
        }
    }

    private static void EmitGlobalConstructor(
        SourceBuilder sb,
        string typeName,
        bool unitySerialization)
    {
        sb.AppendLine($"{typeName}(Kind kind) : this()");
        sb.OpenBrace();
        sb.AppendLine($"this.{(unitySerialization ? UnitySerializationEmitter.RuntimeKindFieldName : "_kind")} = kind;");
        if (unitySerialization)
            sb.AppendLine("this._serializedPayload = null;");
        sb.CloseBrace();
    }

    private static void EmitGlobalFactories(
        SourceBuilder sb,
        UnionDeclaration union,
        OverlapLayoutInfo layout,
        bool unitySerialization)
    {
        foreach (var variant in union.Variants)
        {
            var vl = layout.Variants[variant.Name];
            var typedParams = string.Join(", ",
                variant.Fields.Select(f => $"{f.TypeFullName} {IdentifierUtility.Escape(f.Name)}"));

            bool hasFields = variant.Fields.Length > 0;

            if (!hasFields)
            {
                sb.AppendLine($"public static partial {union.TypeName} {IdentifierUtility.Escape(variant.Name)}()");
                sb.AppendLine($"    => new {union.TypeName}(Kind.{IdentifierUtility.Escape(variant.Name)});");
                continue;
            }

            sb.AppendLine($"public static partial {union.TypeName} {IdentifierUtility.Escape(variant.Name)}({typedParams})");
            if (!unitySerialization)
            {
                sb.AppendLine($"    => new {union.TypeName}(Kind.{IdentifierUtility.Escape(variant.Name)}, " +
                    string.Join(", ", variant.Fields.Select(field => FactoryArgument(field))) + ");");
                continue;
            }

            sb.OpenBrace();
            sb.AppendLine($"var s = new {union.TypeName}(Kind.{IdentifierUtility.Escape(variant.Name)});");

            foreach (var fp in vl.R1Fields)
                sb.AppendLine($"s._{fp.Field.ResolvedPropertyName} = {IdentifierUtility.Escape(fp.Field.Name)};");

            foreach (var fp in vl.R2Fields)
                sb.AppendLine($"s._{fp.Field.ResolvedPropertyName} = {IdentifierUtility.Escape(fp.Field.Name)};");

            foreach (var fp in vl.R3Fields)
                sb.AppendLine($"s._obj_{fp.Field.ResolvedPropertyName} = {IdentifierUtility.Escape(fp.Field.Name)};");

            sb.AppendLine("return s;");
            sb.CloseBrace();
        }
    }

    private static void EmitOrdinaryConstructors(
        SourceBuilder sb,
        UnionDeclaration union)
    {
        var groups = GroupConstructors(union.Variants);
        foreach (var group in groups
            .OrderBy(group => group.Variants[0].Fields.Length == 0 ? 0 : 1)
            .ThenBy(group => group.FirstVariantIndex))
        {
            var first = group.Variants[0];
            var parameterTypes = first.Fields
                .Select(ConstructorParameterType)
                .ToArray();
            var parameters = string.Join(", ", parameterTypes
                .Select((type, index) => $"{type} f{index}"));
            var parameterSuffix = parameters.Length == 0 ? "" : ", " + parameters;

            sb.AppendLine($"{union.TypeName}(Kind kind{parameterSuffix}) : this()");
            sb.OpenBrace();
            sb.AppendLine("this._kind = kind;");

            if (first.Fields.Length > 0)
            {
                var mappings = group.Variants
                    .Select(VariantStorageMapping)
                    .ToList();
                var sameMapping = mappings.Skip(1).All(mapping =>
                    mapping.SequenceEqual(mappings[0], System.StringComparer.Ordinal));

                if (sameMapping)
                {
                    for (var i = 0; i < mappings[0].Count; i++)
                        sb.AppendLine($"this.{mappings[0][i]} = {ConstructorAssignment(
                            first.Fields[i], $"f{i}")};");
                }
                else
                {
                    sb.AppendLine("switch (kind)");
                    sb.OpenBrace();
                    for (var variantIndex = 0; variantIndex < group.Variants.Count; variantIndex++)
                    {
                        var variant = group.Variants[variantIndex];
                        sb.AppendLine($"case Kind.{IdentifierUtility.Escape(variant.Name)}:");
                        sb.Indent();
                        var mapping = mappings[variantIndex];
                        for (var i = 0; i < mapping.Count; i++)
                            sb.AppendLine($"this.{mapping[i]} = {ConstructorAssignment(
                                variant.Fields[i], $"f{i}")};");
                        sb.AppendLine("break;");
                        sb.Dedent();
                    }
                    sb.CloseBrace();
                }
            }

            sb.CloseBrace();
        }
    }

    private static List<ConstructorGroup> GroupConstructors(
        IEnumerable<VariantInfo> variants)
    {
        var groups = new List<ConstructorGroup>();
        var index = 0;
        foreach (var variant in variants)
        {
            var key = string.Join("\u001f", variant.Fields.Select(ConstructorGroupingType));
            var group = groups.FirstOrDefault(candidate =>
                string.Equals(candidate.Key, key, System.StringComparison.Ordinal));
            if (group is null)
            {
                group = new ConstructorGroup(key, index);
                groups.Add(group);
            }
            group.Variants.Add(variant);
            index++;
        }
        return groups;
    }

    private static List<string> VariantStorageMapping(VariantInfo variant)
        => variant.Fields.Select(field =>
            FieldClassifier.Classify(field) == FieldRegion.Boxed
                ? "_obj_" + field.ResolvedPropertyName
                : "_" + field.ResolvedPropertyName).ToList();

    private static string ConstructorParameterType(FieldInfo field)
        => FieldClassifier.Classify(field) switch
        {
            FieldRegion.Unmanaged => field.ConstructorTypeFullName ?? field.ResolvedPropertyTypeFullName,
            FieldRegion.Reference => string.Equals(
                field.TypeFullName,
                "dynamic",
                System.StringComparison.Ordinal)
                ? "object?"
                : NullableReferenceType(field.ConstructorTypeFullName ?? field.ResolvedPropertyTypeFullName),
            _ => field.ConstructorTypeFullName ?? field.ResolvedPropertyTypeFullName,
        };

    private static string FactoryArgument(FieldInfo field)
    {
        var name = IdentifierUtility.Escape(field.Name);
        var constructorType = ConstructorParameterType(field);
        if (string.Equals(field.TypeFullName, "dynamic", System.StringComparison.Ordinal))
            return $"(object?){name}";
        if (FieldClassifier.Classify(field) != FieldRegion.Reference)
            return name;
        return RequiresNullabilityCast(field.TypeFullName, constructorType)
            ? CastThroughObject(constructorType, name)
            : name;
    }

    private static string ConstructorAssignment(
        FieldInfo field,
        string expression)
    {
        if (FieldClassifier.Classify(field) != FieldRegion.Reference)
            return expression;

        var targetType = NullableReferenceType(field.ResolvedPropertyTypeFullName);
        return RequiresNullabilityCast(ConstructorParameterType(field), targetType)
            ? CastThroughObject(targetType, expression)
            : expression;
    }

    private static string CastThroughObject(string targetType, string expression)
        => $"({targetType})(object?){expression}";

    private static bool RequiresNullabilityCast(string sourceType, string targetType)
    {
        var source = TrimOuterNullable(sourceType);
        var target = TrimOuterNullable(targetType);
        return !string.Equals(source, target, System.StringComparison.Ordinal) &&
            (source.IndexOf("?", System.StringComparison.Ordinal) >= 0 ||
             target.IndexOf("?", System.StringComparison.Ordinal) >= 0);
    }

    private static string TrimOuterNullable(string type)
        => type.EndsWith("?", System.StringComparison.Ordinal)
            ? type.Substring(0, type.Length - 1)
            : type;

    private static string ConstructorGroupingType(FieldInfo field)
        => field.ConstructorTypeKey ?? field.TypeFullName;

    private sealed class ConstructorGroup
    {
        public ConstructorGroup(string key, int firstVariantIndex)
        {
            Key = key;
            FirstVariantIndex = firstVariantIndex;
        }

        public string Key { get; }
        public int FirstVariantIndex { get; }
        public List<VariantInfo> Variants { get; } = new List<VariantInfo>();
    }

    private static void EmitProperties(
        SourceBuilder sb,
        OverlapLayoutInfo layout,
        bool hasInitProperties,
        bool unitySerialization)
    {
        foreach (var gf in layout.GlobalR1)
        {
            sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");
            if (hasInitProperties)
            {
                sb.AppendLine($"public {gf.TypeFullName} {IdentifierUtility.Escape(gf.Name)}");
                sb.OpenBrace();
                sb.AppendLine($"get => this._{gf.Name};");
                sb.AppendLine($"init => this._{gf.Name} = value;");
                sb.CloseBrace();
            }
            else
                sb.AppendLine($"public {gf.TypeFullName} {IdentifierUtility.Escape(gf.Name)} => this._{gf.Name};");
        }
        foreach (var gf in layout.GlobalR2)
        {
            sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");
            if (hasInitProperties)
            {
                sb.AppendLine($"public {gf.TypeFullName} {IdentifierUtility.Escape(gf.Name)}");
                sb.OpenBrace();
                sb.AppendLine(unitySerialization || !gf.TypeFullName.EndsWith("?", System.StringComparison.Ordinal)
                    ? $"get => this._{gf.Name}!;"
                    : $"get => this._{gf.Name};");
                sb.AppendLine($"init => this._{gf.Name} = value;");
                sb.CloseBrace();
            }
            else
                sb.AppendLine(unitySerialization || !gf.TypeFullName.EndsWith("?", System.StringComparison.Ordinal)
                    ? $"public {gf.TypeFullName} {IdentifierUtility.Escape(gf.Name)} => this._{gf.Name}!;"
                    : $"public {gf.TypeFullName} {IdentifierUtility.Escape(gf.Name)} => this._{gf.Name};");
        }
        foreach (var gf in layout.GlobalR3)
        {
            sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");
            if (hasInitProperties)
            {
                sb.AppendLine($"public {gf.TypeFullName} {IdentifierUtility.Escape(gf.Name)}");
                sb.OpenBrace();
                sb.AppendLine(unitySerialization
                    ? $"get => this._obj_{gf.Name} is null ? default! : ({gf.TypeFullName})this._obj_{gf.Name};"
                    : $"get => ({gf.TypeFullName})this._obj_{gf.Name}!;");
                sb.AppendLine($"init => this._obj_{gf.Name} = value;");
                sb.CloseBrace();
            }
            else
                sb.AppendLine(unitySerialization
                    ? $"public {gf.TypeFullName} {IdentifierUtility.Escape(gf.Name)} => this._obj_{gf.Name} is null ? default! : ({gf.TypeFullName})this._obj_{gf.Name};"
                    : $"public {gf.TypeFullName} {IdentifierUtility.Escape(gf.Name)} => ({gf.TypeFullName})this._obj_{gf.Name}!;");
        }
    }

    private static void EmitSerializedStorage(SourceBuilder sb, OverlapLayoutInfo layout)
    {
        sb.AppendLine("[global::UnityEngine.SerializeReference]");
        sb.AppendLine($"[FieldOffset({layout.SerializedPayloadOffset})]");
        sb.AppendLine("private __SpireSerializedPayloadBase? _serializedPayload;");
        sb.AppendLine();
    }

    private static string NullableReferenceType(string type)
        => type.EndsWith("?", System.StringComparison.Ordinal) ? type : type + "?";

    private static void EmitGlobalDeconstructs(
        SourceBuilder sb, IEnumerable<VariantInfo> variants, OverlapLayoutInfo layout)
    {
        var variantList = variants.ToList();
        if (variantList.Count == 0) return;

        var groups = GroupByFieldCount(variantList);
        var hasFieldlessVariants = groups.ContainsKey(0);

        if (groups.Count == 1 && hasFieldlessVariants)
        {
            sb.AppendLine();
            sb.AppendLine("public void Deconstruct(out Kind kind, out object? _f0)");
            sb.OpenBrace();
            sb.AppendLine("kind = this.kind;");
            sb.AppendLine("_f0 = null;");
            sb.CloseBrace();
            return;
        }

        var nonZeroGroups = groups
            .Where(g => g.Key > 0)
            .OrderBy(g => g.Key)
            .ToList();

        if (hasFieldlessVariants && nonZeroGroups.Count > 0)
        {
            var smallest = nonZeroGroups[0];
            if (smallest.Value.Count == 1)
                smallest.Value.AddRange(groups[0]);
        }

        foreach (var group in nonZeroGroups)
        {
            var groupVariants = group.Value;
            sb.AppendLine();

            if (groupVariants.Count == 1)
                EmitGlobalTypedDeconstruct(sb, groupVariants[0], layout);
            else
                EmitGlobalObjectDeconstruct(sb, group.Key, groupVariants, layout);
        }
    }

    private static void EmitGlobalTypedDeconstruct(
        SourceBuilder sb, VariantInfo variant, OverlapLayoutInfo layout)
    {
        var vl = layout.Variants[variant.Name];
        var paramList = "out Kind kind";
        foreach (var field in variant.Fields)
            paramList += $", out {field.TypeFullName} {field.Name}";

        sb.AppendLine($"public void Deconstruct({paramList})");
        sb.OpenBrace();
        sb.AppendLine("kind = this.kind;");

        foreach (var field in variant.Fields)
        {
            var region = FieldClassifier.Classify(field);
            switch (region)
            {
                case FieldRegion.Unmanaged:
                    sb.AppendLine($"{IdentifierUtility.Escape(field.Name)} = this._{field.ResolvedPropertyName};");
                    break;
                case FieldRegion.Reference:
                    sb.AppendLine($"{IdentifierUtility.Escape(field.Name)} = this._{field.ResolvedPropertyName}!;");
                    break;
                case FieldRegion.Boxed:
                    sb.AppendLine($"{IdentifierUtility.Escape(field.Name)} = ({field.TypeFullName})this._obj_{field.ResolvedPropertyName}!;");
                    break;
            }
        }

        sb.CloseBrace();
    }

    private static void EmitGlobalObjectDeconstruct(
        SourceBuilder sb, int fieldCount, List<VariantInfo> groupVariants, OverlapLayoutInfo layout)
    {
        var paramList = "out Kind kind";
        for (int i = 0; i < fieldCount; i++)
            paramList += $", out object? f{i}";

        sb.AppendLine($"public void Deconstruct({paramList})");
        sb.OpenBrace();
        sb.AppendLine("kind = this.kind;");

        sb.AppendLine("switch (this.kind)");
        sb.OpenBrace();

        foreach (var variant in groupVariants)
        {
            if (variant.Fields.Length == 0) continue;

            sb.AppendLine($"case Kind.{IdentifierUtility.Escape(variant.Name)}:");
            sb.Indent();

            int fieldIdx = 0;
            foreach (var field in variant.Fields)
            {
                var region = FieldClassifier.Classify(field);
                switch (region)
                {
                    case FieldRegion.Unmanaged:
                        sb.AppendLine($"f{fieldIdx} = this._{field.ResolvedPropertyName};");
                        break;
                    case FieldRegion.Reference:
                        sb.AppendLine($"f{fieldIdx} = this._{field.ResolvedPropertyName};");
                        break;
                    case FieldRegion.Boxed:
                        sb.AppendLine($"f{fieldIdx} = this._obj_{field.ResolvedPropertyName};");
                        break;
                }
                fieldIdx++;
            }

            sb.AppendLine("break;");
            sb.Dedent();
        }

        sb.AppendLine("default:");
        sb.Indent();
        for (int i = 0; i < fieldCount; i++)
            sb.AppendLine($"f{i} = null;");
        sb.AppendLine("break;");
        sb.Dedent();

        sb.CloseBrace(); // switch
        sb.CloseBrace(); // method
    }

    private static Dictionary<int, List<VariantInfo>> GroupByFieldCount(List<VariantInfo> variants)
    {
        var groups = new Dictionary<int, List<VariantInfo>>();
        foreach (var v in variants)
        {
            int count = v.Fields.Length;
            if (!groups.TryGetValue(count, out var list))
            {
                list = new List<VariantInfo>();
                groups[count] = list;
            }
            list.Add(v);
        }
        return groups;
    }
}
