using System.Collections.Generic;
using System.Linq;
using Houtamelo.Spire.Analyzers.SourceGenerators.Model;

namespace Houtamelo.Spire.Analyzers.SourceGenerators.Emit;

internal static class BoxedFieldsEmitter
{
    public static string Emit(UnionDeclaration union)
        => EmitCore(union, unitySerialization: false);

    internal static string EmitUnity(UnionDeclaration union)
        => EmitCore(union, unitySerialization: true);

    private static string EmitCore(UnionDeclaration union, bool unitySerialization)
    {
        var sb = new SourceBuilder();
        var layout = ComputeLayout(union.Variants);
        var unityUsesInitProperties = unitySerialization && union.HasInitProperties;

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.ComponentModel;");
        sb.AppendLine();

        var hasNamespace = !string.IsNullOrEmpty(union.Namespace);
        if (hasNamespace)
        {
            sb.AppendLine($"namespace {union.Namespace}");
            sb.OpenBrace();
        }

        sb.OpenContainingTypes(union.ContainingTypes);

        var typeParams = FormatTypeParams(union.TypeParameters);
        var unionType = union.TypeName + typeParams;
        var accessMod = string.IsNullOrEmpty(union.AccessibilityKeyword) ? "" : union.AccessibilityKeyword + " ";
        var readonlyMod = union.IsReadonly ? "readonly " : "";
        var refMod = union.IsRefStruct ? "ref " : "";
        var unityInterface = unitySerialization
            ? ", global::UnityEngine.ISerializationCallbackReceiver"
            : "";

        sb.AppendLine("[global::Houtamelo.Spire.EnforceInitialization]");
        sb.AppendLine($"{accessMod}{readonlyMod}{refMod}partial {union.DeclarationKeyword} {unionType} : global::Houtamelo.Spire.IDiscriminatedUnion<{unionType}.Kind>{unityInterface}");
        sb.OpenBrace();

        // Kind enum
        EmitKindEnum(sb, union);
        sb.AppendLine();

        // Kind field (backing field + property)
        if (unitySerialization)
        {
            sb.AppendLine("[global::System.NonSerialized]");
            sb.AppendLine($"private Kind {UnitySerializationEmitter.RuntimeKindFieldName};");
        }
        else
        {
            sb.AppendLine("readonly Kind _kind;");
        }
        sb.AppendLine($"public Kind kind => this.{(unitySerialization ? UnitySerializationEmitter.RuntimeKindFieldName : "_kind")};");

        // Boxed slot fields
        for (int i = 0; i < layout.SlotCount; i++)
        {
            sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");
            if (unitySerialization)
                EmitUnitySlot(sb, i, unityUsesInitProperties);
            else if (union.HasInitProperties)
                sb.AppendLine($"internal object? _f{i} {{ get; init; }}");
            else
                sb.AppendLine($"internal readonly object? _f{i};");
        }
        sb.AppendLine();

        if (unitySerialization && layout.SlotCount > 0)
        {
            sb.AppendLine("internal sealed class __SpireBoxedFieldSlot");
            sb.OpenBrace();
            sb.AppendLine("public object? Value;");
            sb.CloseBrace();
            sb.AppendLine();
        }

        // Private constructor
        if (unitySerialization)
            UnitySerializationEmitter.EmitSerializedStorage(sb, union);

        EmitConstructor(sb, union.TypeName, layout.SlotCount, unitySerialization);
        sb.AppendLine();

        // Factory methods
        EmitFactories(sb, union, unionType, layout);

        // Deconstruct overloads
        if (union.GenerateDeconstruct)
            EmitDeconstructs(sb, union.Variants, layout, unitySerialization);

        // Public properties for pattern matching
        EmitProperties(
            sb,
            union.Variants,
            layout,
            union.HasInitProperties || unityUsesInitProperties,
            unitySerialization,
            !unitySerialization || unityUsesInitProperties);

        if (unitySerialization)
            EmitUnityRuntimeFieldAccessors(sb, union, layout);

        // IsVariant properties
        foreach (var variant in union.Variants)
            sb.AppendLine($"public bool Is{variant.Name} => this.kind == Kind.{IdentifierUtility.Escape(variant.Name)};");

        if (unitySerialization)
        {
            UnitySerializationEmitter.EmitCallbacksAndPayloads(
                sb,
                union,
                unionType,
                Enumerable.Range(0, layout.SlotCount)
                    .Select(index => $"this.__s{index} = default!;"));
        }

        ToStringEmitter.EmitStructToString(sb, union);

        sb.CloseBrace(); // type

        sb.CloseContainingTypes(union.ContainingTypes);

        if (hasNamespace)
            sb.CloseBrace(); // namespace

        return sb.ToString();
    }

    #region Layout

    internal sealed class BoxedFieldsLayout
    {
        public int SlotCount;
        public Dictionary<string, VariantMapping> Variants = new Dictionary<string, VariantMapping>();
    }

    internal sealed class VariantMapping
    {
        /// Maps field index (within the variant) to slot index.
        public List<int> FieldToSlot = new List<int>();
    }

    internal static BoxedFieldsLayout ComputeLayout(IEnumerable<VariantInfo> variants)
    {
        var variantList = variants.ToList();
        var layout = new BoxedFieldsLayout();

        // Collect unique field names (sorted for determinism)
        var nameToSlot = new Dictionary<string, int>();
        int slotIndex = 0;
        foreach (var name in variantList
            .SelectMany(v => v.Fields)
            .Select(f => f.ResolvedPropertyName)
            .Distinct()
            .OrderBy(n => n))
        {
            nameToSlot[name] = slotIndex++;
        }

        layout.SlotCount = slotIndex;

        foreach (var variant in variantList)
        {
            var mapping = new VariantMapping();
            foreach (var field in variant.Fields)
                mapping.FieldToSlot.Add(nameToSlot[field.ResolvedPropertyName]);
            layout.Variants[variant.Name] = mapping;
        }

        return layout;
    }

    #endregion

    #region Emit helpers

    private static void EmitKindEnum(SourceBuilder sb, UnionDeclaration union)
    {
        var kindType = OverlapLayoutComputer.KindTypeName(union.Variants.Length);
        sb.AppendLine($"public enum Kind : {kindType}");
        sb.OpenBrace();
        foreach (var variant in union.Variants)
            sb.AppendLine($"{IdentifierUtility.Escape(variant.Name)},");
        sb.CloseBrace();
    }

    private static void EmitUnitySlot(SourceBuilder sb, int index, bool useInitOnly)
    {
        sb.AppendLine($"[global::System.NonSerialized] internal __SpireBoxedFieldSlot? __s{index};");
        _ = useInitOnly;
    }

    private static void EmitConstructor(
        SourceBuilder sb,
        string typeName,
        int slotCount,
        bool unitySerialization)
    {
        var paramList = "Kind kind";
        for (int i = 0; i < slotCount; i++)
            paramList += $", object? f{i}";

        sb.AppendLine($"{typeName}({paramList})");
        sb.OpenBrace();
        sb.AppendLine($"this.{(unitySerialization ? UnitySerializationEmitter.RuntimeKindFieldName : "_kind")} = kind;");
        for (int i = 0; i < slotCount; i++)
            sb.AppendLine(unitySerialization
                ? $"this.__s{i} = f{i} is null ? null : new __SpireBoxedFieldSlot {{ Value = f{i} }};"
                : $"this._f{i} = f{i};");
        if (unitySerialization)
            sb.AppendLine("this._serializedPayload = null;");
        sb.CloseBrace();
    }

    private static void EmitFactories(
        SourceBuilder sb, UnionDeclaration union, string unionType, BoxedFieldsLayout layout)
    {
        foreach (var variant in union.Variants)
        {
            var mapping = layout.Variants[variant.Name];
            var typedParams = string.Join(", ",
                variant.Fields.Select(f => $"{f.TypeFullName} {IdentifierUtility.Escape(f.Name)}"));

            var args = new string[layout.SlotCount];
            for (int i = 0; i < layout.SlotCount; i++)
                args[i] = "null";

            for (int fi = 0; fi < variant.Fields.Length; fi++)
                args[mapping.FieldToSlot[fi]] = IdentifierUtility.Escape(variant.Fields[fi].Name);

            var ctorArgs = "Kind." + IdentifierUtility.Escape(variant.Name);
            if (layout.SlotCount > 0)
                ctorArgs += ", " + string.Join(", ", args);

            sb.AppendLine($"public static partial {unionType} {IdentifierUtility.Escape(variant.Name)}({typedParams})");
            sb.AppendLine($"    => new {unionType}({ctorArgs});");
        }
    }

    private static void EmitProperties(
        SourceBuilder sb,
        IEnumerable<VariantInfo> variants,
        BoxedFieldsLayout layout,
        bool hasInitProperties,
        bool unitySerialization,
        bool useInitOnly)
    {
        var variantList = variants.ToList();
        var emitted = new HashSet<string>();
        foreach (var variant in variantList)
        {
            var mapping = layout.Variants[variant.Name];
            for (int i = 0; i < variant.Fields.Length; i++)
            {
                var field = variant.Fields[i];
                if (!emitted.Add(field.ResolvedPropertyName)) continue;

                int slot = mapping.FieldToSlot[i];
                var runtimeSlot = RuntimeSlot(slot, unitySerialization);
                var valueExpression = unitySerialization
                    ? $"this.{runtimeSlot} is null ? default! : ({field.ResolvedPropertyTypeFullName})this.{runtimeSlot}.Value!"
                    : $"({field.ResolvedPropertyTypeFullName})this.{runtimeSlot}!";
                var getter = valueExpression;
                if (unitySerialization)
                {
                    var validKinds = variantList
                        .Where(candidate => candidate.Fields.Any(candidateField => candidateField.ResolvedPropertyName == field.ResolvedPropertyName))
                        .Select(candidate => $"Kind.{IdentifierUtility.Escape(candidate.Name)}")
                        .ToArray();
                    getter = validKinds.Length == 1
                        ? $"this.kind == {validKinds[0]} ? {valueExpression} : default!"
                        : "this.kind switch\n" +
                            "{\n" +
                            string.Join(",\n", validKinds.Select(kind => $"    {kind} => {valueExpression}")) +
                            ",\n    _ => default!\n}";
                }
                sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");
                if (hasInitProperties)
                {
                    sb.AppendLine($"public {field.ResolvedPropertyTypeFullName} {IdentifierUtility.Escape(field.ResolvedPropertyName)}");
                    sb.OpenBrace();
                    sb.AppendLine($"get => {getter};");
                    var setter = unitySerialization
                        ? (useInitOnly ? "init" : "set")
                        : "init";
                    if (unitySerialization)
                    {
                        var assignment = CanBeNull(field)
                            ? $"value is null ? null : new __SpireBoxedFieldSlot {{ Value = value }}"
                            : "new __SpireBoxedFieldSlot { Value = value }";
                        sb.AppendLine($"{setter} => this.{runtimeSlot} = {assignment};");
                    }
                    else
                    {
                        sb.AppendLine($"{setter} => this.{runtimeSlot} = value;");
                    }
                    sb.CloseBrace();
                }
                else
                {
                    sb.AppendLine($"public {field.ResolvedPropertyTypeFullName} {IdentifierUtility.Escape(field.ResolvedPropertyName)} => {getter};");
                }
            }
        }
    }

    private static void EmitUnityRuntimeFieldAccessors(
        SourceBuilder sb,
        UnionDeclaration union,
        BoxedFieldsLayout layout)
    {
        foreach (var field in union.Variants
                     .SelectMany(variant => variant.Fields)
                     .GroupBy(field => field.ResolvedPropertyName)
                     .Select(group => group.First()))
        {
            var match = layout.Variants
                .SelectMany(pair => pair.Value.FieldToSlot.Select((slot, index) =>
                    (pair.Key, slot, index)))
                .First(item => union.Variants
                    .First(variant => variant.Name == item.Key)
                    .Fields[item.index].ResolvedPropertyName == field.ResolvedPropertyName);
            var setterName = new string(IdentifierUtility.SerializedName(field.ResolvedPropertyName)
                .Select(character => char.IsLetterOrDigit(character) || character == '_' ? character : '_')
                .ToArray());
            sb.AppendLine($"private {field.TypeFullName} __SpireGetSerializedField_{setterName}()");
            sb.OpenBrace();
            sb.AppendLine($"var __SpireValue = this.__s{match.slot}?.Value;");
            sb.AppendLine($"return __SpireValue is null ? default! : ({field.TypeFullName})__SpireValue!;");
            sb.CloseBrace();
        }
    }

    private static void EmitDeconstructs(
        SourceBuilder sb,
        IEnumerable<VariantInfo> variants,
        BoxedFieldsLayout layout,
        bool unitySerialization)
    {
        var variantList = variants.ToList();
        if (variantList.Count == 0) return;

        var groups = GroupByFieldCount(variantList);
        var hasFieldlessVariants = groups.ContainsKey(0);

        if (groups.Count == 1 && hasFieldlessVariants)
        {
            sb.AppendLine();
            sb.AppendLine("public void Deconstruct(out Kind kind, out object? _f0)");
            sb.OpenBrace();
            sb.AppendLine("kind = this.kind;");
            sb.AppendLine("_f0 = null;");
            sb.CloseBrace();
            return;
        }

        var nonZeroGroups = groups
            .Where(g => g.Key > 0)
            .OrderBy(g => g.Key)
            .ToList();

        if (hasFieldlessVariants && nonZeroGroups.Count > 0)
        {
            var smallest = nonZeroGroups[0];
            if (smallest.Value.Count == 1)
                smallest.Value.AddRange(groups[0]);
        }

        foreach (var group in nonZeroGroups)
        {
            var groupVariants = group.Value;
            sb.AppendLine();

            if (groupVariants.Count == 1)
                EmitTypedDeconstruct(sb, groupVariants[0], layout, unitySerialization);
            else
                EmitObjectDeconstruct(sb, group.Key, groupVariants, layout, unitySerialization);
        }
    }

    private static void EmitTypedDeconstruct(
        SourceBuilder sb,
        VariantInfo variant,
        BoxedFieldsLayout layout,
        bool unitySerialization)
    {
        var mapping = layout.Variants[variant.Name];

        var paramList = "out Kind kind";
        foreach (var field in variant.Fields)
            paramList += $", out {field.TypeFullName} {field.Name}";

        sb.AppendLine($"public void Deconstruct({paramList})");
        sb.OpenBrace();
        sb.AppendLine("kind = this.kind;");
        for (int i = 0; i < variant.Fields.Length; i++)
        {
            var field = variant.Fields[i];
            int slot = mapping.FieldToSlot[i];
            var runtimeSlot = RuntimeSlot(slot, unitySerialization);
            sb.AppendLine(unitySerialization
                ? $"{field.Name} = ({field.TypeFullName})this.{runtimeSlot}?.Value!;"
                : $"{field.Name} = ({field.TypeFullName})this.{runtimeSlot}!;");
        }
        sb.CloseBrace();
    }

    private static void EmitObjectDeconstruct(
        SourceBuilder sb,
        int fieldCount,
        List<VariantInfo> groupVariants,
        BoxedFieldsLayout layout,
        bool unitySerialization)
    {
        var paramList = "out Kind kind";
        for (int i = 0; i < fieldCount; i++)
            paramList += $", out object? f{i}";

        sb.AppendLine($"public void Deconstruct({paramList})");
        sb.OpenBrace();
        sb.AppendLine("kind = this.kind;");

        // Need switch because different variants map fields to different slots
        var realVariants = groupVariants.Where(v => v.Fields.Length > 0).ToList();

        if (realVariants.Count > 0)
        {
            sb.AppendLine("switch (this.kind)");
            sb.OpenBrace();

            foreach (var variant in realVariants)
            {
                var mapping = layout.Variants[variant.Name];
                sb.AppendLine($"case Kind.{IdentifierUtility.Escape(variant.Name)}:");
                sb.Indent();
                for (int i = 0; i < variant.Fields.Length; i++)
                {
                    int slot = mapping.FieldToSlot[i];
                    var runtimeSlot = RuntimeSlot(slot, unitySerialization);
                    sb.AppendLine(unitySerialization
                        ? $"f{i} = this.{runtimeSlot}?.Value;"
                        : $"f{i} = this.{runtimeSlot};");
                }
                sb.AppendLine("break;");
                sb.Dedent();
            }

            sb.AppendLine("default:");
            sb.Indent();
            for (int i = 0; i < fieldCount; i++)
                sb.AppendLine($"f{i} = null;");
            sb.AppendLine("break;");
            sb.Dedent();

            sb.CloseBrace(); // switch
        }
        else
        {
            for (int i = 0; i < fieldCount; i++)
                sb.AppendLine($"f{i} = null;");
        }

        sb.CloseBrace(); // method
    }

    private static Dictionary<int, List<VariantInfo>> GroupByFieldCount(List<VariantInfo> variants)
    {
        var groups = new Dictionary<int, List<VariantInfo>>();
        foreach (var v in variants)
        {
            int count = v.Fields.Length;
            if (!groups.TryGetValue(count, out var list))
            {
                list = new List<VariantInfo>();
                groups[count] = list;
            }
            list.Add(v);
        }
        return groups;
    }

    private static string RuntimeSlot(int slot, bool unitySerialization)
        => unitySerialization ? $"__s{slot}" : $"_f{slot}";

    private static bool CanBeNull(FieldInfo field)
        => field.IsReferenceType ||
            field.TypeFullName.EndsWith("?", System.StringComparison.Ordinal) ||
            field.TypeFullName.IndexOf("Nullable<", System.StringComparison.Ordinal) >= 0;

    #endregion

    private static string FormatTypeParams(EquatableArray<string> typeParameters)
    {
        if (typeParameters.Length == 0) return "";
        return "<" + string.Join(", ", typeParameters) + ">";
    }
}
