using System.Collections.Generic;
using System.Linq;
using Houtamelo.Spire.Analyzers.SourceGenerators.Model;

namespace Houtamelo.Spire.Analyzers.SourceGenerators.Emit;

/// Generates struct unions using a byte buffer for unmanaged fields (true overlap)
/// and dedup slots for reference/generic fields. Requires AllowUnsafeBlocks.
internal static class UnsafeOverlapEmitter
{
    public static string Emit(UnionDeclaration union, bool hasInlineArray)
        => EmitCore(union, hasInlineArray, unitySerialization: false);

    internal static string EmitUnity(UnionDeclaration union, bool hasInlineArray)
        => EmitCore(union, hasInlineArray, unitySerialization: true);

    private static string EmitCore(
        UnionDeclaration union,
        bool hasInlineArray,
        bool unitySerialization)
    {
        var sb = new SourceBuilder();
        var layout = ComputeLayout(union.Variants);
        var unityUsesInitProperties = unitySerialization && union.HasInitProperties;

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.ComponentModel;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using System.Runtime.InteropServices;");
        sb.AppendLine();

        var hasNamespace = !string.IsNullOrEmpty(union.Namespace);
        if (hasNamespace)
        {
            sb.AppendLine($"namespace {union.Namespace}");
            sb.OpenBrace();
        }

        sb.OpenContainingTypes(union.ContainingTypes);

        var typeParams = FormatTypeParams(union.TypeParameters);
        var unionType = union.TypeName + typeParams;
        var accessMod = string.IsNullOrEmpty(union.AccessibilityKeyword) ? "" : union.AccessibilityKeyword + " ";
        var readonlyMod = union.IsReadonly ? "readonly " : "";
        var refMod = union.IsRefStruct ? "ref " : "";
        var unityInterface = unitySerialization
            ? ", global::UnityEngine.ISerializationCallbackReceiver"
            : "";

        sb.AppendLine("[global::Houtamelo.Spire.EnforceInitialization]");
        sb.AppendLine($"{accessMod}{readonlyMod}{refMod}partial {union.DeclarationKeyword} {unionType} : global::Houtamelo.Spire.IDiscriminatedUnion<{unionType}.Kind>{unityInterface}");
        sb.OpenBrace();

        // Kind enum
        var kindType = OverlapLayoutComputer.KindTypeName(union.Variants.Length);
        sb.AppendLine($"public enum Kind : {kindType}");
        sb.OpenBrace();
        foreach (var variant in union.Variants)
            sb.AppendLine($"{IdentifierUtility.Escape(variant.Name)},");
        sb.CloseBrace();
        sb.AppendLine();

        // Kind field (backing field + property)
        if (unitySerialization)
        {
            sb.AppendLine("[global::System.NonSerialized]");
            sb.AppendLine($"private Kind {UnitySerializationEmitter.RuntimeKindFieldName};");
        }
        else
        {
            sb.AppendLine("readonly Kind _kind;");
        }
        sb.AppendLine($"public Kind kind => this.{(unitySerialization ? UnitySerializationEmitter.RuntimeKindFieldName : "_kind")};");
        sb.AppendLine();

        // InlineArray buffer (if any unmanaged fields)
        if (layout.BufferSize > 0)
        {
            if (hasInlineArray)
            {
                sb.AppendLine($"[InlineArray({layout.BufferSize})]");
                sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");
                sb.AppendLine("internal struct _Buffer { internal byte _element; }");
                sb.AppendLine();
                sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");
                if (unitySerialization)
                    sb.AppendLine("[global::System.NonSerialized]");
                sb.AppendLine("internal _Buffer _data;");
            }
            else
            {
                EmitFallbackBuffer(sb, layout.BufferSize);
                sb.AppendLine();
                sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");
                if (unitySerialization)
                    sb.AppendLine("[global::System.NonSerialized]");
                sb.AppendLine("internal _Buffer _data;");
            }
            sb.AppendLine();
        }

        // Dedup slots for reference/generic fields — must be plain fields (not
        // auto-properties) because factory methods assign to them directly.
        foreach (var slot in layout.Slots)
        {
            sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");
            var slotType = slot.IsRefSlot ? "object?" : slot.TypeFullName;
            if (unitySerialization)
                EmitUnitySlot(sb, slotType, slot.Index, unityUsesInitProperties);
            else
                sb.AppendLine($"internal {slotType} _s{slot.Index};");
        }
        if (layout.Slots.Count > 0)
            sb.AppendLine();

        // Constructor
        if (unitySerialization)
            UnitySerializationEmitter.EmitSerializedStorage(sb, union);

        EmitConstructor(sb, union.TypeName, layout, unitySerialization);
        sb.AppendLine();

        // Factory methods
        EmitFactories(sb, union, unionType, layout, hasInlineArray, unitySerialization);

        // Deconstruct overloads
        if (union.GenerateDeconstruct)
            EmitDeconstructs(sb, union.Variants, layout, hasInlineArray, unitySerialization);

        // Public properties for pattern matching
        EmitProperties(
            sb,
            union.Variants,
            layout,
            union.HasInitProperties || unityUsesInitProperties,
            hasInlineArray,
            unitySerialization,
            !unitySerialization || unityUsesInitProperties);

        // IsVariant properties
        foreach (var variant in union.Variants)
            sb.AppendLine($"public bool Is{variant.Name} => this.kind == Kind.{IdentifierUtility.Escape(variant.Name)};");

        if (unitySerialization)
        {
            var resetStatements = new List<string>();
            if (layout.BufferSize > 0)
                resetStatements.Add("this._data = default;");
            resetStatements.AddRange(layout.Slots.Select(slot => $"this.__s{slot.Index} = default!;"));
            UnitySerializationEmitter.EmitCallbacksAndPayloads(
                sb,
                union,
                unionType,
                resetStatements);
        }

        ToStringEmitter.EmitStructToString(sb, union);

        sb.CloseBrace(); // type

        sb.CloseContainingTypes(union.ContainingTypes);

        if (hasNamespace)
            sb.CloseBrace();

        return sb.ToString();
    }

    #region Layout

    internal sealed class UnsafeLayout
    {
        public int BufferSize;
        public List<SlotInfo> Slots = new List<SlotInfo>();
        public Dictionary<string, VariantMapping> Variants = new Dictionary<string, VariantMapping>();
        /// Name-pinned buffer offsets
        public Dictionary<string, BufferFieldInfo> NamedBufferFields = new Dictionary<string, BufferFieldInfo>();
        /// Name-pinned slot mappings
        public Dictionary<string, int> NamedSlots = new Dictionary<string, int>();
    }

    internal sealed class BufferFieldInfo
    {
        public string TypeFullName = "";
        public int Offset;
        public int Size;
    }

    internal sealed class SlotInfo
    {
        public int Index;
        public string TypeFullName = "";
        public bool IsRefSlot;
    }

    internal sealed class FieldMapping
    {
        /// True if field goes in the byte buffer, false if in a dedup slot.
        public bool IsBuffer;
        /// Byte offset within the buffer (if IsBuffer).
        public int BufferOffset;
        /// Slot index (if !IsBuffer).
        public int SlotIndex;
    }

    internal sealed class VariantMapping
    {
        public List<FieldMapping> Fields = new List<FieldMapping>();
        public bool HasBufferFields;
        public bool HasSlotFields;
    }

    private static bool IsBufferField(FieldInfo field)
    {
        return field.IsUnmanaged && field.KnownSize.HasValue;
    }

    internal static UnsafeLayout ComputeLayout(IEnumerable<VariantInfo> variants)
    {
        return ComputeLayoutNamePinned(variants.ToList());
    }

    private static UnsafeLayout ComputeLayoutNamePinned(List<VariantInfo> variantList)
    {
        var layout = new UnsafeLayout();

        // Collect unique buffer fields and slot fields by resolved property name.
        var bufferFields = new Dictionary<string, FieldInfo>();
        var slotFields = new Dictionary<string, FieldInfo>();

        foreach (var variant in variantList)
        {
            foreach (var field in variant.Fields)
            {
                if (IsBufferField(field))
                {
                    if (!bufferFields.ContainsKey(field.ResolvedPropertyName))
                        bufferFields[field.ResolvedPropertyName] = field;
                }
                else
                {
                    if (!slotFields.ContainsKey(field.ResolvedPropertyName))
                        slotFields[field.ResolvedPropertyName] = field;
                }
            }
        }

        // Assign global byte offsets for buffer fields (sorted by name)
        int bufferOffset = 0;
        foreach (var kv in bufferFields.OrderBy(x => x.Key))
        {
            layout.NamedBufferFields[kv.Key] = new BufferFieldInfo
            {
                TypeFullName = kv.Value.ResolvedPropertyTypeFullName,
                Offset = bufferOffset,
                Size = kv.Value.KnownSize!.Value,
            };
            bufferOffset += kv.Value.KnownSize!.Value;
        }
        layout.BufferSize = bufferOffset;

        // Assign global slot indices for non-buffer fields (sorted by name)
        int slotIndex = 0;
        foreach (var kv in slotFields.OrderBy(x => x.Key))
        {
            var slotTypeKey = kv.Value.IsReferenceType ? "object?" : kv.Value.ResolvedPropertyTypeFullName;
            bool isRef = kv.Value.IsReferenceType;

            layout.Slots.Add(new SlotInfo
            {
                Index = slotIndex,
                TypeFullName = slotTypeKey,
                IsRefSlot = isRef,
            });
            layout.NamedSlots[kv.Key] = slotIndex;
            slotIndex++;
        }

        // Per-variant field mappings using pinned offsets/slots
        foreach (var variant in variantList)
        {
            var mapping = new VariantMapping();

            foreach (var field in variant.Fields)
            {
                if (IsBufferField(field))
                {
                    var bf = layout.NamedBufferFields[field.ResolvedPropertyName];
                    mapping.Fields.Add(new FieldMapping
                    {
                        IsBuffer = true,
                        BufferOffset = bf.Offset,
                    });
                    mapping.HasBufferFields = true;
                }
                else
                {
                    mapping.Fields.Add(new FieldMapping
                    {
                        IsBuffer = false,
                        SlotIndex = layout.NamedSlots[field.ResolvedPropertyName],
                    });
                    mapping.HasSlotFields = true;
                }
            }

            layout.Variants[variant.Name] = mapping;
        }

        return layout;
    }

    #endregion

    #region Emit

    private static void EmitFallbackBuffer(SourceBuilder sb, int bufferSize)
    {
        int longCount = (bufferSize + 7) / 8;
        int storageSize = longCount * 8;

        sb.AppendLine($"[StructLayout(LayoutKind.Sequential, Size = {storageSize})]");
        sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");
        sb.AppendLine("internal struct _Buffer");
        sb.OpenBrace();
        for (int i = 0; i < longCount; i++)
            sb.AppendLine($"internal long _element{i};");
        sb.CloseBrace();
    }

    private static string BufferByteRef(bool hasInlineArray, string dataExpression, int offset)
    {
        var firstByte = hasInlineArray
            ? $"{dataExpression}[0]"
            : $"Unsafe.As<_Buffer, byte>(ref {dataExpression})";

        return offset == 0
            ? $"ref {firstByte}"
            : $"ref Unsafe.Add(ref {firstByte}, {offset})";
    }

    private static void EmitUnitySlot(
        SourceBuilder sb,
        string slotType,
        int index,
        bool useInitOnly)
    {
        sb.AppendLine($"[global::System.NonSerialized] internal {slotType} __s{index};");
        _ = useInitOnly;
    }

    private static void EmitConstructor(
        SourceBuilder sb,
        string typeName,
        UnsafeLayout layout,
        bool unitySerialization)
    {
        sb.AppendLine($"{typeName}(Kind kind)");
        sb.OpenBrace();
        sb.AppendLine($"this.{(unitySerialization ? UnitySerializationEmitter.RuntimeKindFieldName : "_kind")} = kind;");
        if (layout.BufferSize > 0)
            sb.AppendLine("this._data = default;");
        foreach (var slot in layout.Slots)
            sb.AppendLine(unitySerialization
                ? $"this.__s{slot.Index} = default!;"
                : $"this._s{slot.Index} = default!;");
        if (unitySerialization)
            sb.AppendLine("this._serializedPayload = null;");
        sb.CloseBrace();
    }

    private static void EmitFactories(
        SourceBuilder sb, UnionDeclaration union, string unionType, UnsafeLayout layout,
        bool hasInlineArray,
        bool unitySerialization)
    {
        foreach (var variant in union.Variants)
        {
            var mapping = layout.Variants[variant.Name];
            var typedParams = string.Join(", ",
                variant.Fields.Select(f => $"{f.TypeFullName} {IdentifierUtility.Escape(f.Name)}"));

            bool hasFields = variant.Fields.Length > 0;

            if (!hasFields)
            {
                sb.AppendLine($"public static partial {unionType} {IdentifierUtility.Escape(variant.Name)}()");
                sb.AppendLine($"    => new {unionType}(Kind.{IdentifierUtility.Escape(variant.Name)});");
                continue;
            }

            sb.AppendLine($"public static partial {unionType} {IdentifierUtility.Escape(variant.Name)}({typedParams})");
            sb.OpenBrace();
            sb.AppendLine($"var s = new {unionType}(Kind.{IdentifierUtility.Escape(variant.Name)});");

            for (int i = 0; i < variant.Fields.Length; i++)
            {
                var field = variant.Fields[i];
                var fm = mapping.Fields[i];

                if (fm.IsBuffer)
                {
                    sb.AppendLine($"Unsafe.WriteUnaligned({BufferByteRef(hasInlineArray, "s._data", fm.BufferOffset)}, {IdentifierUtility.Escape(field.Name)});");
                }
                else
                {
                    sb.AppendLine(unitySerialization
                        ? $"s.__s{fm.SlotIndex} = {IdentifierUtility.Escape(field.Name)};"
                        : $"s._s{fm.SlotIndex} = {IdentifierUtility.Escape(field.Name)};");
                }
            }

            sb.AppendLine("return s;");
            sb.CloseBrace();
        }
    }

    private static void EmitProperties(
        SourceBuilder sb,
        IEnumerable<VariantInfo> variants,
        UnsafeLayout layout,
        bool hasInitProperties,
        bool hasInlineArray,
        bool unitySerialization,
        bool useInitOnly)
    {
        var emitted = new HashSet<string>();
        foreach (var variant in variants)
        {
            var mapping = layout.Variants[variant.Name];
            for (int i = 0; i < variant.Fields.Length; i++)
            {
                var field = variant.Fields[i];
                if (!emitted.Add(field.ResolvedPropertyName)) continue;

                var fm = mapping.Fields[i];
                sb.AppendLine("[EditorBrowsable(EditorBrowsableState.Never)]");

                if (fm.IsBuffer)
                {
                    if (hasInitProperties)
                    {
                        sb.AppendLine($"public {field.ResolvedPropertyTypeFullName} {IdentifierUtility.Escape(field.ResolvedPropertyName)}");
                        sb.OpenBrace();
                        sb.AppendLine($"get => Unsafe.ReadUnaligned<{field.TypeFullName}>({BufferByteRef(hasInlineArray, "_data", fm.BufferOffset)});");
                        if (unitySerialization)
                        {
                            var setter = useInitOnly ? "init" : "set";
                            sb.AppendLine($"{setter} {{ Unsafe.WriteUnaligned({BufferByteRef(hasInlineArray, "_data", fm.BufferOffset)}, value); }}");
                        }
                        else
                        {
                            sb.AppendLine($"init => Unsafe.WriteUnaligned({BufferByteRef(hasInlineArray, "_data", fm.BufferOffset)}, value);");
                        }
                        sb.CloseBrace();
                    }
                    else
                    {
                        sb.AppendLine($"public {field.ResolvedPropertyTypeFullName} {IdentifierUtility.Escape(field.ResolvedPropertyName)} => Unsafe.ReadUnaligned<{field.TypeFullName}>({BufferByteRef(hasInlineArray, "_data", fm.BufferOffset)});");
                    }
                }
                else
                {
                    var slotInfo = layout.Slots[fm.SlotIndex];
                    if (hasInitProperties)
                    {
                        sb.AppendLine($"public {field.ResolvedPropertyTypeFullName} {IdentifierUtility.Escape(field.ResolvedPropertyName)}");
                        sb.OpenBrace();
                        if (slotInfo.IsRefSlot)
                            sb.AppendLine(unitySerialization
                                ? $"get => this.{RuntimeSlot(fm.SlotIndex, unitySerialization)} is null ? default! : ({field.ResolvedPropertyTypeFullName})this.{RuntimeSlot(fm.SlotIndex, unitySerialization)};"
                                : $"get => ({field.ResolvedPropertyTypeFullName})this.{RuntimeSlot(fm.SlotIndex, false)}!;");
                        else
                            sb.AppendLine($"get => this.{RuntimeSlot(fm.SlotIndex, unitySerialization)};");
                        var setter = unitySerialization
                            ? (useInitOnly ? "init" : "set")
                            : "init";
                        sb.AppendLine($"{setter} => this.{RuntimeSlot(fm.SlotIndex, unitySerialization)} = value;");
                        sb.CloseBrace();
                    }
                    else
                    {
                        if (slotInfo.IsRefSlot)
                            sb.AppendLine(unitySerialization
                                ? $"public {field.ResolvedPropertyTypeFullName} {IdentifierUtility.Escape(field.ResolvedPropertyName)} => this.{RuntimeSlot(fm.SlotIndex, unitySerialization)} is null ? default! : ({field.ResolvedPropertyTypeFullName})this.{RuntimeSlot(fm.SlotIndex, unitySerialization)};"
                                : $"public {field.ResolvedPropertyTypeFullName} {IdentifierUtility.Escape(field.ResolvedPropertyName)} => ({field.ResolvedPropertyTypeFullName})this.{RuntimeSlot(fm.SlotIndex, false)}!;");
                        else
                            sb.AppendLine($"public {field.ResolvedPropertyTypeFullName} {IdentifierUtility.Escape(field.ResolvedPropertyName)} => this.{RuntimeSlot(fm.SlotIndex, unitySerialization)};");
                    }
                }
            }
        }
    }

    private static void EmitDeconstructs(
        SourceBuilder sb, IEnumerable<VariantInfo> variants, UnsafeLayout layout,
        bool hasInlineArray, bool unitySerialization)
    {
        var variantList = variants.ToList();
        if (variantList.Count == 0) return;

        var groups = GroupByFieldCount(variantList);
        var hasFieldlessVariants = groups.ContainsKey(0);

        if (groups.Count == 1 && hasFieldlessVariants)
        {
            sb.AppendLine();
            sb.AppendLine("public void Deconstruct(out Kind kind, out object? _f0)");
            sb.OpenBrace();
            sb.AppendLine("kind = this.kind;");
            sb.AppendLine("_f0 = null;");
            sb.CloseBrace();
            return;
        }

        var nonZeroGroups = groups
            .Where(g => g.Key > 0)
            .OrderBy(g => g.Key)
            .ToList();

        if (hasFieldlessVariants && nonZeroGroups.Count > 0)
        {
            var smallest = nonZeroGroups[0];
            if (smallest.Value.Count == 1)
                smallest.Value.AddRange(groups[0]);
        }

        foreach (var group in nonZeroGroups)
        {
            var groupVariants = group.Value;
            sb.AppendLine();

            if (groupVariants.Count == 1)
                EmitTypedDeconstruct(sb, groupVariants[0], layout, hasInlineArray, unitySerialization);
            else
                EmitObjectDeconstruct(sb, group.Key, groupVariants, layout, hasInlineArray, unitySerialization);
        }
    }

    private static void EmitTypedDeconstruct(
        SourceBuilder sb, VariantInfo variant, UnsafeLayout layout, bool hasInlineArray,
        bool unitySerialization)
    {
        var mapping = layout.Variants[variant.Name];

        var paramList = "out Kind kind";
        foreach (var field in variant.Fields)
            paramList += $", out {field.TypeFullName} {IdentifierUtility.Escape(field.Name)}";

        sb.AppendLine($"public void Deconstruct({paramList})");
        sb.OpenBrace();
        sb.AppendLine("kind = this.kind;");

        for (int i = 0; i < variant.Fields.Length; i++)
        {
            var field = variant.Fields[i];
            var fm = mapping.Fields[i];

            if (fm.IsBuffer)
            {
                sb.AppendLine($"{IdentifierUtility.Escape(field.Name)} = Unsafe.ReadUnaligned<{field.TypeFullName}>({BufferByteRef(hasInlineArray, "_data", fm.BufferOffset)});");
            }
            else
            {
                var slotInfo = layout.Slots[fm.SlotIndex];
                if (slotInfo.IsRefSlot)
                    sb.AppendLine($"{IdentifierUtility.Escape(field.Name)} = ({field.TypeFullName})this.{RuntimeSlot(fm.SlotIndex, unitySerialization)}!;");
                else
                    sb.AppendLine($"{IdentifierUtility.Escape(field.Name)} = this.{RuntimeSlot(fm.SlotIndex, unitySerialization)};");
            }
        }

        sb.CloseBrace();
    }

    private static void EmitObjectDeconstruct(
        SourceBuilder sb, int fieldCount, List<VariantInfo> groupVariants, UnsafeLayout layout,
        bool hasInlineArray, bool unitySerialization)
    {
        var paramList = "out Kind kind";
        for (int i = 0; i < fieldCount; i++)
            paramList += $", out object? f{i}";

        sb.AppendLine($"public void Deconstruct({paramList})");
        sb.OpenBrace();
        sb.AppendLine("kind = this.kind;");

        var realVariants = groupVariants.Where(v => v.Fields.Length > 0).ToList();

        if (realVariants.Count > 0)
        {
            sb.AppendLine("switch (this.kind)");
            sb.OpenBrace();

            foreach (var variant in realVariants)
            {
                var mapping = layout.Variants[variant.Name];
                sb.AppendLine($"case Kind.{IdentifierUtility.Escape(variant.Name)}:");
                sb.Indent();

                for (int i = 0; i < variant.Fields.Length; i++)
                {
                    var field = variant.Fields[i];
                    var fm = mapping.Fields[i];

                    if (fm.IsBuffer)
                    {
                        sb.AppendLine($"f{i} = Unsafe.ReadUnaligned<{field.TypeFullName}>({BufferByteRef(hasInlineArray, "_data", fm.BufferOffset)});");
                    }
                    else
                    {
                        sb.AppendLine($"f{i} = this.{RuntimeSlot(fm.SlotIndex, unitySerialization)};");
                    }
                }

                sb.AppendLine("break;");
                sb.Dedent();
            }

            sb.AppendLine("default:");
            sb.Indent();
            for (int i = 0; i < fieldCount; i++)
                sb.AppendLine($"f{i} = null;");
            sb.AppendLine("break;");
            sb.Dedent();

            sb.CloseBrace(); // switch
        }
        else
        {
            for (int i = 0; i < fieldCount; i++)
                sb.AppendLine($"f{i} = null;");
        }

        sb.CloseBrace(); // method
    }

    private static Dictionary<int, List<VariantInfo>> GroupByFieldCount(List<VariantInfo> variants)
    {
        var groups = new Dictionary<int, List<VariantInfo>>();
        foreach (var v in variants)
        {
            int count = v.Fields.Length;
            if (!groups.TryGetValue(count, out var list))
            {
                list = new List<VariantInfo>();
                groups[count] = list;
            }
            list.Add(v);
        }
        return groups;
    }

    private static string FormatTypeParams(EquatableArray<string> typeParameters)
    {
        if (typeParameters.Length == 0) return "";
        return "<" + string.Join(", ", typeParameters) + ">";
    }

    private static string RuntimeSlot(int slot, bool unitySerialization)
        => unitySerialization ? $"__s{slot}" : $"_s{slot}";

    #endregion
}
