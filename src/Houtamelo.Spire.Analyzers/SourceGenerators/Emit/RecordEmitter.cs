using Houtamelo.Spire.Analyzers.SourceGenerators.Model;

namespace Houtamelo.Spire.Analyzers.SourceGenerators.Emit;

internal static class RecordEmitter
{
    public static string Emit(UnionDeclaration union)
    {
        var sb = new SourceBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        var hasNamespace = !string.IsNullOrEmpty(union.Namespace);
        if (hasNamespace)
            sb.OpenNamespace(union.Namespace);

        sb.OpenContainingTypes(union.ContainingTypes);

        var typeParams = DeclarationFormatting.FormatRawTypeParameters(union.TypeParameters);
        var unionType = union.TypeName + typeParams;

        var accessMod = DeclarationFormatting.FormatAccessibility(union.AccessibilityKeyword);
        sb.AppendLine($"{accessMod}abstract partial record {unionType}");
        sb.OpenBrace();

        // The default constructor accessibility inside a record is private.
        sb.AppendLine($"{union.TypeName}() {{}}");
        sb.AppendLine();

        // Variant records — just re-declare as sealed partial
        foreach (var variant in union.Variants)
        {
            var variantAccess = DeclarationFormatting.FormatAccessibility(variant.AccessibilityKeyword);
            sb.AppendLine($"{variantAccess}sealed partial record {variant.Name};");
        }

        sb.AppendLine();
        foreach (var variant in union.Variants)
            sb.AppendLine($"public bool Is{variant.Name} => this is {variant.Name};");

        sb.CloseBrace(); // type

        sb.CloseContainingTypes(union.ContainingTypes);

        if (hasNamespace)
            sb.CloseNamespace();

        return sb.ToString();
    }

}
