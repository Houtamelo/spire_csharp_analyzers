    private static string FormatTypeSegment(string name)
    {
        var genericStart = name.IndexOf('<');
        if (genericStart < 0)
        {
            var metadataArityStart = name.LastIndexOf('`');
            if (metadataArityStart >= 0 &&
                int.TryParse(name.Substring(metadataArityStart + 1), out var metadataArity) &&
                metadataArity > 0)
            {
                var metadataName = EscapeIdentifier(name.Substring(0, metadataArityStart));
                return metadataName + "<" + string.Join(", ", Enumerable.Repeat("", metadataArity)) + ">";
            }

            return EscapeIdentifier(name);
        }

        var baseName = EscapeIdentifier(name.Substring(0, genericStart));
        var genericEnd = name.LastIndexOf('>');
        if (genericEnd <= genericStart)
            return baseName;

        var arguments = name.Substring(genericStart + 1, genericEnd - genericStart - 1)
            .Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries)
            .ToArray();
        return baseName + "<" + string.Join(", ", Enumerable.Repeat("", arguments.Length)) + ">";
    }

