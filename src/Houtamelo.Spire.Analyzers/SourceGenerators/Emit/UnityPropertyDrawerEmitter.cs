using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Houtamelo.Spire.Analyzers.SourceGenerators.Model;

namespace Houtamelo.Spire.Analyzers.SourceGenerators.Emit;

/// Emits the small per-union adapter for the shared Unity Editor drawer.
///
/// Preview isolation, native controls, replacement commits, and Undo live in the
/// compilation-scoped support template. This adapter only supplies metadata.
internal static class UnityPropertyDrawerEmitter
{
    private static readonly HashSet<string> CSharpKeywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch",
        "char", "checked", "class", "const", "continue", "decimal", "default",
        "delegate", "do", "double", "else", "enum", "event", "explicit", "extern",
        "false", "finally", "fixed", "float", "for", "foreach", "goto", "if",
        "implicit", "in", "int", "interface", "internal", "is", "lock", "long",
        "namespace", "new", "null", "object", "operator", "out", "override", "params",
        "private", "protected", "public", "readonly", "ref", "return", "sbyte",
        "sealed", "short", "sizeof", "stackalloc", "static", "string", "struct",
        "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong",
        "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile",
        "while", "add", "alias", "ascending", "async", "await", "by", "descending",
        "dynamic", "equals", "file", "from", "get", "global", "group", "init",
        "into", "join", "let", "managed", "nameof", "notnull", "on", "orderby",
        "partial", "record", "remove", "required", "select", "set", "unmanaged",
        "value", "var", "when", "where", "with", "yield",
    };

    public static string Emit(UnionDeclaration union)
    {
        if (union.Variants.Length == 0)
            return string.Empty;

        var builder = new StringBuilder();
        var drawerName = GetDrawerName(union);
        var targetType = FormatTargetType(union);
        var hasNamespace = !string.IsNullOrEmpty(union.Namespace);

        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#if UNITY_EDITOR");
        builder.AppendLine("using System;");
        builder.AppendLine("using UnityEditor;");
        builder.AppendLine("using CustomPropertyDrawer = global::UnityEditor.CustomPropertyDrawer;");
        builder.AppendLine("using DrawerBase = global::Houtamelo.Spire.Generated.__SpireUnityPropertyDrawer;");
        builder.AppendLine("using DrawerMetadata = global::Houtamelo.Spire.Generated.__SpireUnityDrawerMetadata;");
        builder.AppendLine("using VariantMetadata = global::Houtamelo.Spire.Generated.__SpireUnityVariantMetadata;");
        builder.AppendLine();

        if (hasNamespace)
        {
            builder.Append("namespace ").Append(FormatNamespace(union.Namespace)).AppendLine(" {");
        }

        // Keep generic drawers top-level. A drawer nested in a generic
        // containing type would itself be generic, which Unity cannot
        // instantiate for an open generic CustomPropertyDrawer. Nongeneric
        // private nested unions need a drawer inside their containing type so
        // the generated typeof expression remains accessible.
        var nestedDrawer = NeedsNestedDrawer(union) && !HasGenericContainingType(union);
        var indent = 0;
        if (nestedDrawer)
        {
            foreach (var containingType in union.ContainingTypes)
            {
                var access = string.IsNullOrEmpty(containingType.AccessibilityKeyword) ||
                    containingType.AccessibilityKeyword == "private"
                    ? string.Empty
                    : containingType.AccessibilityKeyword + " ";
                var keyword = containingType.Keyword == "static class"
                    ? "static partial class"
                    : "partial " + containingType.Keyword;
                AppendIndented(
                    builder,
                    indent,
                    access + keyword + " " + EscapeIdentifier(containingType.Name));
                AppendIndentedOpenBrace(builder, indent);
                indent++;
            }
        }

        AppendIndented(builder, indent,
            "[@CustomPropertyDrawer(typeof(" + targetType + "), true)]");
        AppendIndented(builder, indent,
            "internal sealed class " + drawerName + " : DrawerBase");
        AppendIndentedOpenBrace(builder, indent);
        indent++;
        AppendIndented(builder, indent,
            "static readonly DrawerMetadata Metadata = new DrawerMetadata(");
        if (union.TypeParameters.Length == 0 && !HasGenericContainingType(union))
            AppendIndented(builder, indent + 1, "typeof(" + targetType + "),");
        else
            AppendIndented(builder, indent + 1, "null,");

        AppendIndented(builder, indent + 1, "new[]");
        AppendIndentedOpenBrace(builder, indent + 1);
        foreach (var variant in union.Variants)
        {
            AppendIndented(builder, indent + 2,
                "new VariantMetadata(");
            AppendIndented(builder, indent + 3, Quote(variant.Name) + ",");
            AppendIndented(builder, indent + 3, Quote(PayloadTypeName(union, variant.Name)) + ",");
            AppendIndented(
                builder,
                indent + 3,
                HasAlias(variant)
                    ? Quote(PayloadTypeName(union, variant.FormerlySerializedAs!)) + ","
                    : "null,");

            if (variant.Fields.Length == 0)
            {
                AppendIndented(builder, indent + 3, "Array.Empty<string>()");
            }
            else
            {
                AppendIndented(builder, indent + 3, "new[]");
                AppendIndentedOpenBrace(builder, indent + 3);
                foreach (var field in variant.Fields)
                    AppendIndented(builder, indent + 4, Quote(VariantPayloadEmitter.BackingFieldName(field)) + ",");
                AppendIndented(builder, indent + 3, "}");
            }

            AppendIndented(builder, indent + 2, "),");
        }
        AppendIndented(builder, indent + 1, "});");
        AppendIndented(builder, indent, "public " + drawerName + "() : base(Metadata) {}");

        indent--;
        AppendIndented(builder, indent, "}");

        if (nestedDrawer)
        {
            for (var i = 0; i < union.ContainingTypes.Length; i++)
            {
                indent--;
                AppendIndented(builder, indent, "}");
            }
        }

        if (hasNamespace)
            builder.AppendLine("}");

        builder.AppendLine("#endif");
        return builder.ToString();
    }

    private static string FormatTargetType(UnionDeclaration union)
    {
        var parts = new List<string>();
        if (!string.IsNullOrEmpty(union.Namespace))
        {
            var namespaceParts = union.Namespace
                .Split(new[] { '.' }, StringSplitOptions.RemoveEmptyEntries)
                .Select(EscapeIdentifier);
            parts.Add("global::" + string.Join(".", namespaceParts));
        }

        foreach (var containingType in union.ContainingTypes)
            parts.Add(FormatTypeSegment(containingType));

        var typeName = EscapeIdentifier(union.TypeName);
        if (union.TypeParameters.Length > 0)
            typeName += "<" + string.Join(", ", Enumerable.Repeat("", union.TypeParameters.Length)) + ">";

        parts.Add(typeName);
        return string.Join(".", parts);
    }

    private static string FormatNamespace(string namespaceName)
    {
        return string.Join(
            ".",
            namespaceName
                .Split(new[] { '.' }, StringSplitOptions.RemoveEmptyEntries)
                .Select(EscapeIdentifier));
    }

    private static string GetDrawerName(UnionDeclaration union)
    {
        var parts = new List<string> { "__SpireUnityPropertyDrawer" };
        foreach (var containingType in union.ContainingTypes)
            parts.Add(SanitizeIdentifier(containingType.Name));
        parts.Add(SanitizeIdentifier(union.TypeName));
        if (union.TypeParameters.Length > 0)
            parts.Add("Arity" + union.TypeParameters.Length);
        return string.Join("_", parts);
    }

    private static string FormatTypeSegment(string name)
    {
        var genericStart = name.IndexOf('<');
        if (genericStart < 0)
        {
            var metadataArityStart = name.LastIndexOf('`');
            if (metadataArityStart >= 0 &&
                int.TryParse(name.Substring(metadataArityStart + 1), out var metadataArity) &&
                metadataArity > 0)
            {
                var metadataName = EscapeIdentifier(name.Substring(0, metadataArityStart));
                return metadataName + "<" + string.Join(", ", Enumerable.Repeat("", metadataArity)) + ">";
            }

            return EscapeIdentifier(name);
        }

        var baseName = EscapeIdentifier(name.Substring(0, genericStart));
        var genericEnd = name.LastIndexOf('>');
        if (genericEnd <= genericStart)
            return baseName;

        var arguments = name.Substring(genericStart + 1, genericEnd - genericStart - 1)
            .Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries)
            .ToArray();
        return baseName + "<" + string.Join(", ", Enumerable.Repeat("", arguments.Length)) + ">";
    }

    private static string FormatTypeSegment(ContainingTypeInfo containingType)
    {
        if (containingType.TypeParameters.Length == 0)
            return FormatTypeSegment(containingType.Name);

        return EscapeIdentifier(containingType.Name) + "<" +
            string.Join(", ", Enumerable.Repeat("", containingType.TypeParameters.Length)) + ">";
    }

    private static bool HasGenericContainingType(UnionDeclaration union)
    {
        return union.ContainingTypes.Any(containingType =>
            containingType.TypeParameters.Length > 0 ||
            containingType.Name.IndexOf('<') >= 0 ||
            containingType.Name.IndexOf('`') >= 0);
    }

    private static bool NeedsNestedDrawer(UnionDeclaration union)
    {
        if (union.ContainingTypes.Length == 0)
            return false;

        // A nested type without an explicit modifier is private by default.
        if (string.IsNullOrEmpty(union.AccessibilityKeyword) ||
            IsInaccessibleFromTopLevel(union.AccessibilityKeyword))
            return true;

        return union.ContainingTypes.Any(containingType =>
            IsInaccessibleFromTopLevel(containingType.AccessibilityKeyword));
    }

    private static bool IsInaccessibleFromTopLevel(string accessibility)
    {
        return accessibility == "private" ||
            accessibility == "protected" ||
            accessibility == "private protected";
    }

    private static string EscapeIdentifier(string name)
    {
        if (name.StartsWith("@", StringComparison.Ordinal))
            name = name.Substring(1);
        return CSharpKeywords.Contains(name) ? "@" + name : name;
    }

    private static string SanitizeIdentifier(string name)
    {
        if (name.StartsWith("@", StringComparison.Ordinal))
            name = name.Substring(1);

        var builder = new StringBuilder(name.Length);
        foreach (var character in name)
            builder.Append(char.IsLetterOrDigit(character) || character == '_' ? character : '_');
        return builder.Length == 0 ? "Union" : builder.ToString();
    }

    private static string Quote(string value)
        => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    private static string SerializedName(string name)
        => name.StartsWith("@", StringComparison.Ordinal) ? name.Substring(1) : name;

    private static string PayloadTypeName(UnionDeclaration union, string variantName)
    {
        var raw = GeneratedAliasEmitter.TypesName(union) + "+Variants+" + SerializedName(variantName);
        var chars = raw
            .Select(character => char.IsLetterOrDigit(character) || character is '_' or '+' ? character : '_')
            .ToArray();
        var safe = chars.Length == 0 ? "Value" : new string(chars);
        return safe;
    }

    private static bool HasAlias(VariantInfo variant)
        => variant.HasFormerlySerializedAs;

    private static void AppendIndented(StringBuilder builder, int indent, string line)
    {
        builder.Append(' ', indent * 4).AppendLine(line);
    }

    private static void AppendIndentedOpenBrace(StringBuilder builder, int indent)
    {
        if (builder.Length > 0 && builder[^1] == '\n')
        {
            builder.Length--;
            if (builder.Length > 0 && builder[^1] == '\r')
                builder.Length--;
            builder.Append(" {").AppendLine();
            return;
        }

        AppendIndented(builder, indent, "{");
    }
}
